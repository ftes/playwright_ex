defmodule Mix.Tasks.PlaywrightEx.Gen.Protocol do
  @shortdoc "Generates the protocol validator and metainfo from upstream protocol specs"
  @upstream "utils/generate_channels.js"
  @moduledoc """
  Port of upstream `#{@upstream}` (the validator and metainfo parts).

      mix playwright_ex.gen.protocol [<playwright-repo>]

  `<playwright-repo>` is a checkout of microsoft/playwright at the pinned driver version,
  by default `PlaywrightEx.Upstream.ensure!/0`. Its `packages/protocol/spec/*.yml` are loaded like
  `utils/protocol_spec.js` does, with the yaml parser bundled in the installed driver's
  playwright-core, so no npm install is needed. Writes:

    * `lib/playwright_ex/protocol/validator.ex` (upstream `packages/protocol/src/validator.ts`):
      one `scheme/1` clause per scheme, as data interpreted by
      `PlaywrightEx.Protocol.ValidatorPrimitives` instead of composed validator functions.
    * `lib/playwright_ex/protocol/metainfo.ex` (upstream `packages/isomorphic/protocolMetainfo.ts`).

  Not ported: `channels.d.ts`/`structs.d.ts` (TypeScript types) and the spec lint checks.
  """
  use Mix.Task

  @validator "lib/playwright_ex/protocol/validator.ex"
  @metainfo "lib/playwright_ex/protocol/metainfo.ex"
  @header "# This file is generated by `mix playwright_ex.gen.protocol` from packages/protocol/spec/*.yml, do not edit manually.\n"

  # utils/protocol_spec.js loadProtocol(), printing ordered [key, value] pairs for objects.
  @load_protocol """
  const fs = require('fs');
  const path = require('path');
  const { yaml } = require(path.join(process.argv[2], 'lib', 'utilsBundle.js'));
  const specDir = path.join(process.argv[1], 'packages', 'protocol', 'spec');
  const protocol = {};
  for (const file of fs.readdirSync(specDir).filter(f => f.endsWith('.yml')).sort()) {
    const doc = yaml.parse(fs.readFileSync(path.join(specDir, file), 'utf-8'));
    for (const [name, value] of Object.entries(doc)) {
      if (name in protocol)
        throw new Error(`Duplicate top-level definition "${name}" in ${file}`);
      protocol[name] = value;
    }
  }
  const ordered = v => Array.isArray(v) ? v.map(ordered) : (v && typeof v === 'object') ? { o: Object.entries(v).map(([k, x]) => [k, ordered(x)]) } : v;
  process.stdout.write(JSON.stringify(ordered(protocol)));
  """

  @impl Mix.Task
  def run([]), do: run([PlaywrightEx.Upstream.ensure!()])

  def run([repo]) do
    {node, [cli]} = PlaywrightEx.Driver.ensure_installed()
    {json, 0} = System.cmd(node, ["-e", @load_protocol, Path.expand(repo), Path.dirname(cli)])
    protocol = json |> JSON.decode!() |> ordered() |> entries()

    channels = for {name, value} <- protocol, get(value, "type") == "interface", into: %{}, do: {name, value}
    mixins = for {name, value} <- protocol, get(value, "type") == "mixin", into: %{}, do: {name, value}

    derived =
      for {name, item} <- protocol, get(item, "type") == "interface", get(item, "extends"), reduce: %{} do
        acc -> Map.update(acc, get(item, "extends"), [name], &(&1 ++ [name]))
      end

    ctx = %{channels: channels, mixins: mixins, derived: derived}
    {schemes, metainfo} = generate(ctx, protocol)

    write(@validator, validator_source(schemes))
    write(@metainfo, metainfo_source(metainfo))
  end

  def run(_), do: Mix.raise("Usage: mix playwright_ex.gen.protocol [<playwright-repo>]")

  defp generate(ctx, protocol) do
    acc = %{schemes: {[], %{}}, metainfo: []}

    acc =
      Enum.reduce(protocol, acc, fn {name, item}, acc ->
        case get(item, "type") do
          "interface" -> interface(ctx, acc, name, item)
          "object" -> add_scheme(acc, name, object_type(ctx, get(item, "properties")))
          "enum" -> add_scheme(acc, name, {:enum, literals(get(item, "literals"))})
          "mixin" -> acc
        end
      end)

    {schemes, values} = acc.schemes
    {Enum.map(Enum.reverse(schemes), &{&1, values[&1]}), Enum.reverse(acc.metainfo)}
  end

  defp interface(ctx, acc, name, item) do
    derived = Map.get(ctx.derived, name, [])

    # Initializer: the closest ancestor that declares one.
    ancestor = ancestor_with_initializer(ctx, item)

    acc =
      add_scheme(
        acc,
        name <> "Initializer",
        if(get(ancestor, "initializer"),
          do: object_type(ctx, get(ancestor, "initializer")),
          else: {:optional, {:object, []}}
        )
      )

    acc =
      Enum.reduce(entries(get(item, "events")), acc, fn {event_name, event}, acc ->
        params_name = name <> title_case(event_name) <> "Event"
        acc = add_scheme(acc, params_name, params(ctx, event))
        Enum.reduce(derived, acc, &add_scheme(&2, &1 <> title_case(event_name) <> "Event", {:type, params_name}))
      end)

    Enum.reduce(entries(get(item, "commands")), acc, fn {method_name, method}, acc ->
      acc =
        Enum.reduce([name | derived], acc, fn class_name, acc ->
          %{acc | metainfo: [{class_name <> "." <> method_name, method_metainfo(method)} | acc.metainfo]}
        end)

      params_name = name <> title_case(method_name) <> "Params"
      acc = add_scheme(acc, params_name, params(ctx, method))
      acc = Enum.reduce(derived, acc, &add_scheme(&2, &1 <> title_case(method_name) <> "Params", {:type, params_name}))

      result_name = name <> title_case(method_name) <> "Result"

      result =
        if get(method, "returns"), do: object_type(ctx, get(method, "returns")), else: {:optional, {:object, []}}

      acc = add_scheme(acc, result_name, result)
      acc = Enum.reduce(derived, acc, &add_scheme(&2, &1 <> title_case(method_name) <> "Result", {:type, result_name}))

      if details = get(method, "errorDetails") do
        details_name = name <> title_case(method_name) <> "ErrorDetails"
        acc = add_scheme(acc, details_name, object_type(ctx, details))

        Enum.reduce(
          derived,
          acc,
          &add_scheme(&2, &1 <> title_case(method_name) <> "ErrorDetails", {:type, details_name})
        )
      else
        acc
      end
    end)
  end

  defp ancestor_with_initializer(ctx, item) do
    cond do
      get(item, "initializer") -> item
      extends = get(item, "extends") -> ancestor_with_initializer(ctx, ctx.channels[extends])
      true -> item
    end
  end

  defp params(ctx, item) do
    if get(item, "parameters"), do: object_type(ctx, get(item, "parameters")), else: {:optional, {:object, []}}
  end

  @metainfo_props [
    {"internal", :internal},
    {"title", :title},
    {"subtitle", :subtitle},
    {"renderParams", :renderParams}
  ]
  @metainfo_flags [:slowMo, :snapshot, :pause, :input, :isAutoWaiting]

  defp method_metainfo(method) do
    props = for {key, atom} <- @metainfo_props, value = get(method, key), do: {atom, value}
    flags = for flag <- @metainfo_flags, value = get(get(method, "flags"), Atom.to_string(flag)), do: {flag, value}
    group = if group = get(method, "group"), do: [group: group], else: []
    props ++ flags ++ group
  end

  # JS: `scheme.X = ...`; a later assignment replaces the value but keeps the position.
  defp add_scheme(%{schemes: {names, values}} = acc, name, scheme) do
    names = if Map.has_key?(values, name), do: names, else: [name | names]
    %{acc | schemes: {names, Map.put(values, name, scheme)}}
  end

  # inlineType(type) -> scheme
  defp inline_type(ctx, type) when is_binary(type) do
    {type, optional} =
      if String.ends_with?(type, "?"), do: {String.trim_trailing(type, "?"), true}, else: {type, false}

    scheme =
      cond do
        type == "binary" -> :binary
        type == "json" -> :any
        type in ~w(string boolean undefined int float) -> String.to_atom(type)
        type == "number" -> raise ~s(Use "int" or "float" instead of "number" in protocol.yml)
        Map.has_key?(ctx.channels, type) -> {:channel, Map.get(ctx.derived, type, []) ++ [type]}
        type == "Channel" -> {:channel, :*}
        true -> {:type, type}
      end

    {scheme, optional}
  end

  defp inline_type(ctx, type) do
    kind = get(type, "type")
    optional = String.ends_with?(kind, "?")

    scheme =
      cond do
        String.starts_with?(kind, "array") -> {:array, wrap(inline_type(ctx, get(type, "items")))}
        String.starts_with?(kind, "enum") -> {:enum, literals(get(type, "literals"))}
        String.starts_with?(kind, "object") -> {:object, properties(ctx, get(type, "properties"))}
        true -> raise "Invalid item: #{inspect(type)}"
      end

    {scheme, optional}
  end

  defp wrap({scheme, _optional}), do: scheme

  defp properties(ctx, props) do
    Enum.flat_map(entries(props), fn
      {"$mixin" <> _, mixin} ->
        properties(ctx, get(ctx.mixins[mixin], "properties"))

      {name, value} ->
        {scheme, optional} = inline_type(ctx, value)
        [{String.to_atom(name), if(optional, do: {:optional, scheme}, else: scheme)}]
    end)
  end

  defp object_type(ctx, props), do: {:object, properties(ctx, props)}

  defp validator_source(schemes) do
    clauses =
      Enum.map_join(schemes, "\n", fn {name, scheme} ->
        "def scheme(#{inspect(name)}), do: #{inspect(scheme, limit: :infinity)}"
      end)

    """
    #{@header}
    defmodule PlaywrightEx.Protocol.Validator do
      @upstream "packages/protocol/src/validator.ts"
      @moduledoc "Generated port of `\#{@upstream}`: protocol schemes as data, see `PlaywrightEx.Protocol.ValidatorPrimitives`."

      defdelegate find_validator(type, method, kind), to: PlaywrightEx.Protocol.ValidatorPrimitives
      defdelegate maybe_find_validator(type, method, kind), to: PlaywrightEx.Protocol.ValidatorPrimitives
      defdelegate create_metadata_validator(), to: PlaywrightEx.Protocol.ValidatorPrimitives
      defdelegate create_wait_info_validator(), to: PlaywrightEx.Protocol.ValidatorPrimitives

      @doc "The scheme named `name`, or `nil`."
      #{clauses}
      def scheme(_name), do: nil
    end
    """
  end

  defp metainfo_source(metainfo) do
    entries = Enum.map_join(metainfo, ",\n", fn {name, info} -> "#{inspect(name)} => %{#{map_body(info)}}" end)

    """
    #{@header}
    defmodule PlaywrightEx.Protocol.Metainfo do
      @upstream "packages/isomorphic/protocolMetainfo.ts"
      @moduledoc "Generated port of `\#{@upstream}`."

      @doc "Method metainfo by `\\"Type.method\\"`: `internal`, `title`, `subtitle`, `renderParams`, flags and `group`."
      def method_metainfo do
        %{
          #{entries}
        }
      end

      @doc "Metainfo of `type.method`, or `nil`."
      def get_metainfo(%{type: type, method: method}), do: Map.get(method_metainfo(), "\#{type}.\#{method}")
    end
    """
  end

  defp map_body(info), do: Enum.map_join(info, ", ", fn {k, v} -> "#{k}: #{inspect(v)}" end)

  defp write(path, source) do
    File.mkdir_p!(Path.dirname(path))
    File.write!(path, [Code.format_string!(source, line_length: 120), "\n"])
    Mix.shell().info("Wrote #{path}")
  end

  # Ordered objects come in as %{"o" => [[key, value], ...]}.
  defp ordered(%{"o" => pairs}), do: {:ordered, Enum.map(pairs, fn [k, v] -> {k, ordered(v)} end)}
  defp ordered(list) when is_list(list), do: Enum.map(list, &ordered/1)
  defp ordered(other), do: other

  defp entries({:ordered, pairs}), do: Enum.map(pairs, fn {k, v} -> {k, v || {:ordered, []}} end)
  defp entries(nil), do: []

  defp get({:ordered, pairs}, key), do: with({_, v} <- List.keyfind(pairs, key, 0), do: v)
  defp get(_, _key), do: nil

  defp title_case(<<first::utf8, rest::binary>>), do: String.upcase(<<first::utf8>>) <> rest

  # `'${literal}'` upstream: a YAML `null` literal is the string "null".
  defp literals(literals), do: Enum.map(literals, &if(&1 == nil, do: "null", else: to_string(&1)))
end

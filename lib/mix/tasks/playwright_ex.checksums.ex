defmodule Mix.Tasks.PlaywrightEx.Checksums do
  @shortdoc "Fetches and writes priv/driver_checksums.exs for the pinned versions (roll step)"
  @moduledoc """
  Usage: `mix playwright_ex.checksums [DRIVER_VERSION NODE_VERSION]`

  Reads the npm `dist.integrity` (sha512 SRI) of `playwright-core@<driver>` from the registry
  and Node's `SHASUMS256.txt` from nodejs.org, then writes `priv/driver_checksums.exs`. Given
  versions, it also writes them to the `DRIVER_VERSION` and `NODE_VERSION` files that
  `PlaywrightEx.Driver` reads: that is the bump (editing the files first fails compilation, so
  this task could not run). Trust is anchored at roll time; installs only compare against the
  committed values.
  """
  use Mix.Task

  alias PlaywrightEx.Driver

  @impl true
  def run(args) do
    {driver, node} =
      case args do
        [d, n] -> {d, n}
        [] -> {Driver.version(), Driver.node_version()}
      end

    tmp = Path.join(System.tmp_dir!(), "pw-checksums-#{System.unique_integer([:positive])}")
    File.mkdir_p!(tmp)

    try do
      meta = Path.join(tmp, "meta.json")
      Driver.download!("https://registry.npmjs.org/playwright-core/#{driver}", meta)
      integrity = meta |> File.read!() |> JSON.decode!() |> get_in(["dist", "integrity"])
      "sha512-" <> _ = integrity

      shasums = Path.join(tmp, "SHASUMS256.txt")
      Driver.download!("https://nodejs.org/dist/v#{node}/SHASUMS256.txt", shasums)

      sums =
        for line <- shasums |> File.read!() |> String.split("\n", trim: true),
            [hex, file] = String.split(line, ~r/\s+/, parts: 2),
            into: %{},
            do: {file, hex}

      node_sums =
        for p <- Driver.platforms(), into: %{} do
          file =
            if String.starts_with?(p, "win-"),
              do: "node-v#{node}-#{p}.zip",
              else: "node-v#{node}-#{p}.tar.gz"

          {p, Map.fetch!(sums, file)}
        end

      content =
        inspect(
          %{
            driver_version: driver,
            node_version: node,
            playwright_core: integrity,
            node: node_sums
          },
          pretty: true,
          limit: :infinity
        )

      File.write!(
        "priv/driver_checksums.exs",
        "# Generated by `mix playwright_ex.checksums`. Do not edit.\n" <> content <> "\n"
      )

      if args != [] do
        File.write!("DRIVER_VERSION", driver <> "\n")
        File.write!("NODE_VERSION", node <> "\n")
      end

      Mix.shell().info("Wrote priv/driver_checksums.exs for playwright-core #{driver}, node #{node}")
    after
      File.rm_rf!(tmp)
    end
  end
end

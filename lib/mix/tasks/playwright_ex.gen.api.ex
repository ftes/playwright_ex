defmodule Mix.Tasks.PlaywrightEx.Gen.Api do
  @shortdoc "Generates the public API facade from upstream api.json"
  @moduledoc """
  Generates the public API (`PlaywrightEx.Browser`, ...) from upstream's `api.json`.

      mix playwright_ex.gen.api [--check] [<playwright-repo>]

  `<playwright-repo>` is a checkout of microsoft/playwright at the pinned driver version, by
  default `PlaywrightEx.Upstream.ensure!/0`. `api.json` is built from its `docs/src/api` with
  upstream `utils/doclint/generateApiJson.js`, filtered to `langs: js` with upstream's own
  `filterForLanguage`, using the installed driver's Node (no npm install); a JS-only option with a
  variant of the same type for the other clients takes that variant's doc (`input-timeout`, not
  `input-timeout-js` with the test runner's config), so do the fields of a JS-only `optionsOr<Name>`
  object (`waitForEvent`'s `timeout`). Then
  `Mix.PlaywrightEx.ApiRules` applies the Elixir rules.

  Writes `lib/playwright_ex/api/<class>.ex` for every class and member the rules keep (what is
  out of scope is dropped there, with its reason). Each function sets the API name for errors,
  converts options (`PlaywrightEx.Runtime.Facade`), carries docs and specs, and calls
  `PlaywrightEx.Client.<Class>` with the JS arity (receiver plus JS arguments), so a client
  function that is missing is a compile warning (`--warnings-as-errors` in CI). Docs render from
  the `spec` markdown AST; options get a `@type <member>_options`. Their prose names what Elixir
  has, never inside code blocks: `nil` (`:null` passed in), option atoms and argument names for
  JS names (`ignoreCase`, `pageFunction`), enum atoms (`'light'`), function links for JS calls
  (`page.goto()`); `Mix.PlaywrightEx.ApiRules` overrides the rest, `PlaywrightEx.ApiDocsTest`
  checks it. A JS example with a translation
  in `test/examples` (Mix.PlaywrightEx.Examples) is rendered in Elixir; a translation whose JS
  upstream no longer has fails the run.

    * `async: true` members: `name/n` returns `{:ok, value} | {:error, exception}` (`:ok` for
      `void`), `name!/n` returns the value or raises.
    * Waits (`"promise"`, see `Mix.PlaywrightEx.ApiRules`): `name/n` returns a `PlaywrightEx.Promise`,
      `name!/n` awaits it; their docs show starting the wait before the action.
    * `async: false` members and properties: plain values.
    * Handles: a class whose client module exports `__struct_fields__/0` gets the struct
      (`%PlaywrightEx.Page{}`) and `__client__/0`, its client module (`PlaywrightEx.Runtime.Heap.impl/1`).
    * Classes with events: `on/3`, `once/3`, `add_listener/3`, `remove_listener/3`, `off/3`,
      `prepend_listener/3` with event atoms (`:disconnected`), as `types.d.ts` has them; any
      string too for `"openEvents"` classes (`CDPSession`, see `Mix.PlaywrightEx.ApiRules`). The
      call runs in `PlaywrightEx.Runtime.Facade.listen/1`: the listener is a user listener.

  `--check` writes nothing and fails if a file is out of date (`mix playwright_ex.parity` runs it).
  """
  use Mix.Task

  alias Mix.PlaywrightEx.ApiRules
  alias Mix.PlaywrightEx.Examples

  @dir "lib/playwright_ex/api"
  @header "# This file is generated by `mix playwright_ex.gen.api` from api.json, do not edit manually.\n"
  @listener_methods ~w(on once addListener removeListener off prependListener)
  @reserved ~w(after and catch do else end false fn in nil not or rescue true when)
  # Receivers of JS calls in prose (`context.newPage()`) besides the class names (`browserContext`).
  @receiver_aliases %{"context" => "BrowserContext", "handle" => "JSHandle", "session" => "CDPSession"}

  # api.json for the JS client: generateApiJson.js after `documentation.filterForLanguage('js')`.
  # linkUtils.js requires lodash/kebabCase, inlined here.
  @load_api """
  const path = require('path');
  const Module = require('module');
  const repo = process.argv[1];
  const load = Module._load;
  Module._load = function (request, ...rest) {
    if (request === 'lodash/kebabCase.js' || request === 'lodash/kebabCase')
      return s => s.replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[^A-Za-z0-9]+/).filter(Boolean).join('-').toLowerCase();
    return load.call(this, request, ...rest);
  };
  const apiParser = require(path.join(repo, 'utils', 'doclint', 'api_parser.js'));
  const parseApi = apiParser.parseApi;
  // A JS-only argument or option with a variant of the same type for the other clients
  // (`input-timeout-js` and `input-timeout`) takes that variant's doc: the JS one describes the
  // test runner (`actionTimeout` in its config).
  const otherLangs = o => o.langs.only && !o.langs.only.includes('js');
  const otherLangsDocs = (members, seen) => {
    for (const m of members) {
      const other = String(m.langs.only) === 'js' && members.find(o =>
        o.name === m.name && otherLangs(o) && o.type?.expression === m.type?.expression);
      if (other)
        m.spec = other.spec;
      otherLangsDocsOfType(m.type, seen);
    }
  };
  // The object of a JS-only `optionsOr<Name>` argument (`waitForEvent(event, optionsOrPredicate)`)
  // has the other clients' options: `timeout` takes `wait-for-event-timeout`, not the test runner's.
  const optionsOrDocs = args => {
    const options = args.find(a => a.name === 'options');
    for (const arg of args) {
      if (String(arg.langs.only) !== 'js' || !arg.name.startsWith('optionsOr') || !options)
        continue;
      for (const prop of (arg.type.union || []).flatMap(t => t.properties || [])) {
        const other = options.type.properties.find(o =>
          o.name === prop.name && otherLangs(o) && o.type?.expression === prop.type?.expression);
        if (other)
          prop.spec = other.spec;
      }
    }
  };
  const otherLangsDocsOfType = (type, seen) => {
    if (!type || seen.has(type))
      return;
    seen.add(type);
    otherLangsDocs(type.properties || [], seen);
    for (const t of [...(type.union || []), ...(type.args || []), ...(type.templates || []), type.returnType])
      otherLangsDocsOfType(t, seen);
  };
  apiParser.parseApi = (...args) => {
    const documentation = parseApi(...args);
    const seen = new Set();
    for (const clazz of documentation.classesArray) {
      for (const member of clazz.membersArray) {
        optionsOrDocs(member.argsArray);
        otherLangsDocs(member.argsArray, seen);
      }
    }
    documentation.filterForLanguage(process.argv[2]);
    return documentation;
  };
  require(path.join(repo, 'utils', 'doclint', 'generateApiJson.js'));
  """

  @impl Mix.Task
  def run(argv) do
    {opts, args} = OptionParser.parse!(argv, strict: [check: :boolean])

    repo =
      case args do
        [] -> PlaywrightEx.Upstream.ensure!()
        [repo] -> repo
        _ -> Mix.raise("Usage: mix playwright_ex.gen.api [--check] [<playwright-repo>]")
      end

    Mix.Task.run("compile")

    if opts[:check] do
      case check(repo) do
        [] -> Mix.shell().info("gen.api: up to date")
        stale -> Mix.raise("gen.api: out of date, run mix playwright_ex.gen.api: #{Enum.join(stale, ", ")}")
      end
    else
      files = sources(repo)
      for {path, source} <- files, File.read(path) != {:ok, source}, do: write(path, source)

      for path <- generated_files() -- Map.keys(files) do
        File.rm!(path)
        Mix.shell().info("Removed #{path}")
      end
    end
  end

  @doc false
  # Generated files that differ from what is on disk (or should not exist).
  def check(repo) do
    files = sources(repo)
    stale = for {path, source} <- files, File.read(path) != {:ok, source}, do: path
    stale ++ (generated_files() -- Map.keys(files))
  end

  defp generated_files do
    for path <- Path.wildcard(Path.join(@dir, "*.ex")), String.starts_with?(File.read!(path), @header), do: path
  end

  @doc false
  # `lang`: the client whose view of the docs to load ("js", "python" for the callback forms).
  def api_json(repo, lang \\ "js") do
    {node, _} = PlaywrightEx.Driver.ensure_installed()
    {json, 0} = System.cmd(node, ["-e", @load_api, Path.expand(repo), lang])
    JSON.decode!(json)
  end

  @doc false
  # %{path => source} for every class.
  def sources(repo) do
    api = api_json(repo)
    classes = ApiRules.apply(api, api_json(repo, "python"))
    examples = Examples.load()

    case Examples.stale(examples, js_blocks(classes)) do
      [] ->
        :ok

      stale ->
        Mix.raise("gen.api: examples for JS upstream no longer has (test/examples):\n\n" <> Enum.join(stale, "\n\n"))
    end

    ctx = %{
      classes: Map.new(classes, &{&1["name"], &1}),
      # Every upstream class, for links to playwright.dev.
      all: MapSet.new(api, & &1["name"]),
      examples: examples,
      # JS names in prose (`baseURL`, `page.goto()`), see `prose_code/2`.
      options: option_names(classes),
      option_literals: option_literals(classes),
      receivers: Map.new(classes, &{receiver_name(&1["name"]), &1["name"]}) |> Map.merge(@receiver_aliases),
      names: %{},
      literals: %{},
      input: false
    }

    Map.new(classes, fn class ->
      path = Path.join(@dir, Macro.underscore(class["name"]) <> ".ex")
      {path, format(class_source(Map.put(ctx, :class, class["name"]), class))}
    end)
  end

  # The text of every JS code block in the docs (trailing blank lines dropped, as in `Examples`).
  defp js_blocks(%{"type" => "code", "codeLang" => "js", "lines" => lines}), do: [js_text(lines)]
  defp js_blocks(term) when is_map(term), do: term |> Map.values() |> js_blocks()
  defp js_blocks(term) when is_list(term), do: Enum.flat_map(term, &js_blocks/1)
  defp js_blocks(_term), do: []

  defp js_text(lines), do: lines |> Enum.join("\n") |> String.trim_trailing()

  # `Expect` (the assertion classes, see `Mix.PlaywrightEx.ApiRules`) is implemented by the matchers.
  defp impl("Expect"), do: PlaywrightEx.Matchers.Expect
  defp impl(class_name), do: Module.concat(PlaywrightEx.Client, class_name)
  defp facade(class_name), do: Module.concat(PlaywrightEx, class_name)

  # The matcher's function in `customAsyncMatchers`, with the JS arity (this, receiver, arguments).
  defp matcher_function(%{"matcher" => %{"name" => name}} = member) do
    fun = PlaywrightEx.Matchers.Expect.custom_async_matchers()[name]

    if !is_function(fun, 2 + length(member["args"])),
      do: Mix.raise("gen.api: matcher #{name} is missing from PlaywrightEx.Matchers.Expect.custom_async_matchers/0")

    fun
  end

  # --- modules -----------------------------------------------------------------

  defp class_source(ctx, class) do
    name = class["name"]
    members = class["members"] |> Enum.reject(&(&1["kind"] == "event")) |> Enum.uniq_by(& &1["alias"])
    events = for m <- class["members"], m["kind"] == "event", do: m
    receiver = receiver(name, members)
    ctx = Map.put(ctx, :receiver, receiver)
    listeners = if events != [], do: @listener_methods, else: []

    # `@events` maps event atoms to JS names, for listeners and `event` arguments (`wait_for_event`).
    events_table =
      if listeners != [] or Enum.any?(members, &event_arg?/1),
        do: "@events #{render({:map, Enum.map(events, &{event_atom(&1), String.downcase(&1["name"])})})}"

    handle_type =
      if name != "Expect",
        do: """
        @typedoc "A `#{name}` handle. Compare handles with `==`, their fields are internal."
        @type t :: #{struct_type(ctx, name)}

        #{handle_struct(name)}
        """

    body = """
    #{handle_type}#{event_type(events)}

    #{events_table}

    #{Enum.map_join(members, "\n\n", &member_source(ctx, class, &1, receiver))}

    #{listeners_source(ctx, class, events, listeners, receiver)}
    """

    """
    #{@header}
    defmodule #{inspect(facade(name))} do
      #{String.replace(since(class), "@doc", "@moduledoc")}@moduledoc #{doc(module_doc(ctx, class, events))}

      #{if String.contains?(body, "Facade."), do: "alias PlaywrightEx.Runtime.Facade"}

      #{body}
    end
    """
  end

  # A subclass handle is one too (an `ElementHandle` is a `JSHandle`).
  defp struct_type(ctx, name) do
    subclasses = for {sub, %{"extends" => ^name}} <- ctx.classes, do: sub

    if handle?(name),
      do: Enum.join(["%__MODULE__{}" | Enum.map(Enum.sort(subclasses), &"%#{inspect(facade(&1))}{}")], " | "),
      else: "term()"
  end

  # The handle struct of a class whose client module has one (`__struct_fields__/0`), and the
  # client module implementing it (`PlaywrightEx.Runtime.Heap.impl/1`).
  defp handle_struct(name) do
    if handle?(name),
      do: """
      defstruct #{Macro.to_string(impl(name).__struct_fields__())}

      @doc false
      def __client__, do: #{inspect(impl(name))}
      """
  end

  defp handle?(name), do: Code.ensure_loaded?(impl(name)) and function_exported?(impl(name), :__struct_fields__, 0)

  defp module_doc(ctx, class, events) do
    sections([
      md(class["spec"], ctx),
      class["extends"] && extends_doc(ctx, class["extends"]),
      events != [] &&
        "## Events\n\n" <>
          Enum.map_join(events, "\n\n", &event_doc(ctx, &1, class["since"])),
      "The examples alias the modules they use (`alias PlaywrightEx.{Locator, Page}`)."
    ])
  end

  defp extends_doc(ctx, parent) do
    if Map.has_key?(ctx.classes, parent),
      do: "Extends `#{inspect(facade(parent))}`: its functions take this handle too.",
      else: "Extends `#{parent}`."
  end

  defp event_doc(ctx, event, since) do
    doc = md(event["spec"], ctx)
    doc = if newer?(event["since"], since), do: inline_join("*Since #{version(event["since"])}.*", doc), else: doc
    sections(["### `#{inspect(event_atom(event))}`", doc])
  end

  defp event_type([]), do: ""

  defp event_type(events),
    do: "@type event :: " <> Enum.map_join(events, " | ", &inspect(event_atom(&1)))

  # --- members -----------------------------------------------------------------

  # `expect(x).not` (`"negate"`, see `Mix.PlaywrightEx.ApiRules`): the struct of a negated receiver.
  defp member_source(ctx, _class, %{"negate" => receivers} = member, _receiver) do
    receiver_spec = Enum.map_join(receivers, " | ", &"#{inspect(facade(&1))}.t()")

    """
    @typedoc "A negated receiver (`not_/1`): `expect(actual).not` in JS."
    @type t(actual) :: %__MODULE__{actual: actual, isNot: true}
    @typedoc "A negated receiver of any matcher."
    @type t :: t(#{receiver_spec})

    defstruct [:actual, isNot: true]

    #{since(member)}@doc #{doc(member_doc(ctx, member, []))}
    @spec not_(actual) :: t(actual) when actual: #{receiver_spec}
    def not_(%__MODULE__{}),
      do: raise(ArgumentError, "expect.not: the receiver is negated already (JS has no expect(x).not.not)")

    def not_(actual), do: %__MODULE__{actual: actual}
    """
  end

  # `to_have_text(locator, expected, options)`: `createMatcher(name, info, actual, matcher)(...args)`.
  defp member_source(ctx, class, %{"matcher" => matcher} = member, _receiver) do
    name = snake(member["alias"])
    api_name = api_name(class["name"], member["alias"])
    receiver = matcher_receiver(matcher["receivers"])
    vars = Enum.map(member["args"], &var(&1["name"]))
    attrs = for {arg, var} <- Enum.zip(member["args"], vars), schema = arg_schema(ctx, arg), do: {arg, var, schema}
    params = [receiver | Enum.map(Enum.zip(member["args"], vars), &param/1)]
    fun = matcher_function(member)
    info = Function.info(fun)
    capture = "&#{inspect(info[:module])}.#{info[:name]}/#{info[:arity]}"

    call =
      "#{inspect(impl(class["name"]))}.create_matcher(#{inspect(matcher["name"])}, %{isNot: is_not}, " <>
        "#{receiver}, #{capture}).([#{Enum.join(vars, ", ")}])"

    m = %{params: params, function: nil, or_options: or_options(member["args"], vars)}
    receiver_spec = Enum.map_join(matcher["receivers"], " | ", &"#{inspect(facade(&1))}.t()")
    # A negated receiver (`not_/1`) takes the place of the receiver, not of a negated one.
    receiver_spec = if matcher["isNot"], do: receiver_spec, else: "#{receiver_spec} | t(#{receiver_spec})"
    m = Map.put(m, :spec_args, [receiver_spec | Enum.map(member["args"], &arg_spec(ctx, &1, name))])

    conversions =
      Enum.join(
        [
          "{#{receiver}, is_not} = Facade.negated(#{receiver}, #{matcher["isNot"]}, #{inspect(api_name)})"
          | Enum.map(attrs, &conversion(name, api_name, &1))
        ],
        "\n"
      )

    attributes =
      Enum.join(
        [
          Enum.map_join(attrs, "\n", &attribute(name, &1))
          | for(%{"name" => "options"} = arg <- member["args"], do: options_type(ctx, name, length(params), arg))
        ],
        "\n\n"
      )

    """
    #{attributes}

    #{since(member)}#{deprecated(member)}@doc #{doc(member_doc(ctx, member, member["args"]))}
    #{spec(name, m, ":ok | {:error, PlaywrightEx.error()}")}
    #{clauses(m, name)}def #{head(name, params, m.or_options)} do
      #{conversions}
      Facade.matcher(#{receiver}, fn -> #{call} end)
    end

    #{since(member)}#{deprecated(member)}@doc "Like `#{name}/#{length(params)}`, but raises `ExUnit.AssertionError` when the expectation is not met."
    #{spec(name <> "!", m, ":ok")}
    #{clauses(m, name <> "!")}def #{head(name <> "!", params, m.or_options)} do
      #{conversions}
      Facade.matcher!(#{receiver}, fn -> #{call} end)
    end
    """
  end

  defp member_source(ctx, class, member, receiver) do
    name = snake(member["alias"])
    # A callback form (`expect_popup`) is named after the wait it starts (`page.waitForEvent`).
    callback = member["callback"]
    api_name = api_name(class["name"], if(callback, do: callback["call"], else: member["alias"]))
    args = if callback, do: with_action(member["args"]), else: member["args"]
    vars = Enum.map(args, &var(&1["name"]))
    attrs = for {arg, var} <- Enum.zip(args, vars), schema = arg_schema(ctx, arg), do: {arg, var, schema}
    params = [receiver | Enum.map(Enum.zip(args, vars), &param/1)]
    void? = get_in(member, ["type", "name"]) == "void"
    examples = wait_examples(ctx, class, member, receiver, args, vars)
    doc = promise_doc(member_doc(ctx, member, args), member, length(params), examples)

    attributes =
      Enum.join(
        [
          Enum.map_join(attrs, "\n", &attribute(name, &1))
          | for(%{"name" => "options"} = arg <- args, do: options_type(ctx, name, length(params), arg))
        ],
        "\n\n"
      )

    function = Enum.find_value(args, &(&1["name"] == "options" && &1["function"]))
    or_options = or_options(args, vars)

    member_def(member, %{
      name: name,
      api_name: inspect(api_name),
      receiver: receiver,
      params: params,
      head: head(name, params, function || or_options),
      function: function,
      or_options: or_options,
      attributes: attributes,
      conversions: Enum.map_join(attrs, "\n", &conversion(name, api_name, &1)),
      call: options_dictionary(ctx, member, client_call(class, member, receiver, vars)),
      void?: void?,
      spec_args: ["t()" | Enum.map(args, &arg_spec(ctx, &1, name))],
      return: if(void?, do: ":ok", else: return_spec(ctx, member)),
      examples: examples,
      docs: since(member) <> deprecated(member) <> "@doc #{doc(doc)}"
    })
  end

  # A dictionary of option objects (device descriptors, see `Mix.PlaywrightEx.ApiRules`): the
  # client's JS keys become the option keys of `member["options"]` (`"Browser.newContext"`).
  defp options_dictionary(ctx, %{"options" => options}, call) do
    [class_name, member_name] = String.split(options, ".")
    member = Enum.find(ctx.classes[class_name]["members"], &(&1["name"] == member_name))
    %{"type" => %{"properties" => props}} = Enum.find(member["args"], &(&1["name"] == "options"))
    # A map literal in api.json order.
    keys =
      Enum.map_join(
        Enum.uniq_by(props, & &1["name"]),
        ", ",
        &"#{key(String.to_atom(&1["name"]))} #{inspect(atom(&1["name"]))}"
      )

    "Facade.options_dictionary(#{call}, %{#{keys}})"
  end

  defp options_dictionary(_ctx, _member, call), do: call

  defp return_spec(_ctx, %{"options" => options}) do
    [class_name, member_name] = String.split(options, ".")
    "%{optional(String.t()) => #{inspect(facade(class_name))}.#{snake(member_name)}_options()}"
  end

  defp return_spec(ctx, member), do: type_spec(ctx, member["type"], :out)

  # With options in place of an optional argument (`"orOptions"`), the arity without the options
  # takes them too.
  defp spec(name, %{spec_args: args} = m, return) do
    short =
      if m.or_options do
        {head, [arg, options]} = Enum.split(args, -2)
        "\n@spec #{name}(#{Enum.join(head ++ ["#{arg} | #{options}"], ", ")}) :: #{return}"
      end

    "@spec #{name}(#{Enum.join(args, ", ")}) :: #{return}#{short}"
  end

  defp no_default(param), do: param |> String.split(" \\\\ ") |> hd()

  # The head of the main clause: without defaults after a bodiless head with them (`clauses/2`).
  defp head(name, params, clauses?),
    do: "#{name}(#{Enum.join(if(clauses?, do: Enum.map(params, &no_default/1), else: params), ", ")})"

  # The variable of the argument whose place the options may take (`"orOptions"`, see `Mix.PlaywrightEx.ApiRules`).
  defp or_options(args, vars), do: Enum.find_value(Enum.zip(args, vars), fn {arg, var} -> arg["orOptions"] && var end)

  # Clauses for values in another argument's place (see `Mix.PlaywrightEx.ApiRules`), after a
  # bodiless head with the defaults: a function in place of the options (`optionsOrPredicate`) is
  # option `function`, options in place of an optional argument (`"orOptions"`) leave it `nil`.
  defp clauses(%{function: nil, or_options: nil}, _name), do: ""

  defp clauses(m, name) do
    plain = Enum.map(m.params, &no_default/1)

    function =
      if function = m.function do
        var = snake(function)
        fun_params = Enum.map(plain, &if(&1 == "options", do: var, else: &1))
        call_args = Enum.map(plain, &if(&1 == "options", do: "#{var}: #{var}", else: &1))

        """
        def #{name}(#{Enum.join(fun_params, ", ")}) when is_function(#{var}),
          do: #{name}(#{Enum.join(call_args, ", ")})
        """
      end

    or_options =
      if var = m.or_options do
        opt_params = Enum.map(plain, &(%{var => "options", "options" => "[]"}[&1] || &1))
        call_args = Enum.map(plain, &if(&1 == var, do: "nil", else: &1))

        """
        def #{name}(#{Enum.join(opt_params, ", ")}) when is_list(options) or (is_map(options) and not is_struct(options)),
          do: #{name}(#{Enum.join(call_args, ", ")})
        """
      end

    """
    def #{name}(#{Enum.join(m.params, ", ")})

    #{function}
    #{or_options}
    """
  end

  defp param({%{"name" => "options"}, var}), do: "#{var} \\\\ []"
  defp param({%{"required" => true}, var}), do: var
  defp param({_, var}), do: "#{var} \\\\ nil"

  defp attribute(_name, {_, _, :event}), do: ""
  defp attribute(name, {_, var, schema}), do: "@#{name}_#{var} #{render(schema)}"

  # Options that may be a result of the member (`"result"`, see `Mix.PlaywrightEx.ApiRules`).
  defp conversion(name, api_name, {%{"name" => "options", "result" => %{"ignored" => ignored}}, var, _}),
    do:

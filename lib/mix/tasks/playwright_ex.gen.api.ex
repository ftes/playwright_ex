defmodule Mix.Tasks.PlaywrightEx.Gen.Api do
  @shortdoc "Generates the public API facade from upstream api.json"
  @moduledoc """
  Generates the public API (`PlaywrightEx.Browser`, ...) from upstream's `api.json`.

      mix playwright_ex.gen.api [--check] [<playwright-repo>]

  `<playwright-repo>` is a checkout of microsoft/playwright at the pinned driver version, by
  default `PlaywrightEx.Upstream.ensure!/0`. `api.json` is built from its `docs/src/api` with
  upstream `utils/doclint/generateApiJson.js`, filtered to `langs: js` with upstream's own
  `filterForLanguage`, using the installed driver's Node (no npm install). Then
  `Mix.PlaywrightEx.ApiRules` applies the Elixir rules.

  Writes `lib/playwright_ex/api/<class>.ex` for every class and member the rules keep (what is
  out of scope is dropped there, with its reason). Each function sets the API name for errors,
  converts options (`PlaywrightEx.Runtime.Facade`), carries docs and specs, and calls
  `PlaywrightEx.Client.<Class>` with the JS arity (receiver plus JS arguments), so a client
  function that is missing is a compile warning (`--warnings-as-errors` in CI). Docs render from
  the `spec` markdown AST; options get a `@type <member>_options`.

    * `async: true` members: `name/n` returns `{:ok, value} | {:error, exception}` (`:ok` for
      `void`), `name!/n` returns the value or raises.
    * `async: false` members and properties: plain values, called without the baton.
    * Classes with events: `on/3`, `once/3`, `add_listener/3`, `remove_listener/3`, `off/3`,
      `prepend_listener/3` with event atoms (`:disconnected`), as `types.d.ts` has them; any
      string too for `"openEvents"` classes (`CDPSession`, see `Mix.PlaywrightEx.ApiRules`).

  `--check` writes nothing and fails if a file is out of date (`mix playwright_ex.parity` runs it).
  """
  use Mix.Task

  alias Mix.PlaywrightEx.ApiRules

  @dir "lib/playwright_ex/api"
  @header "# This file is generated by `mix playwright_ex.gen.api` from api.json, do not edit manually.\n"
  @listener_methods ~w(on once addListener removeListener off prependListener)
  @reserved ~w(after and catch do else end false fn in nil not or rescue true when)

  # api.json for the JS client: generateApiJson.js after `documentation.filterForLanguage('js')`.
  # linkUtils.js requires lodash/kebabCase, inlined here.
  @load_api """
  const path = require('path');
  const Module = require('module');
  const repo = process.argv[1];
  const load = Module._load;
  Module._load = function (request, ...rest) {
    if (request === 'lodash/kebabCase.js' || request === 'lodash/kebabCase')
      return s => s.replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[^A-Za-z0-9]+/).filter(Boolean).join('-').toLowerCase();
    return load.call(this, request, ...rest);
  };
  const apiParser = require(path.join(repo, 'utils', 'doclint', 'api_parser.js'));
  const parseApi = apiParser.parseApi;
  apiParser.parseApi = (...args) => {
    const documentation = parseApi(...args);
    documentation.filterForLanguage(process.argv[2]);
    return documentation;
  };
  require(path.join(repo, 'utils', 'doclint', 'generateApiJson.js'));
  """

  @impl Mix.Task
  def run(argv) do
    {opts, args} = OptionParser.parse!(argv, strict: [check: :boolean])

    repo =
      case args do
        [] -> PlaywrightEx.Upstream.ensure!()
        [repo] -> repo
        _ -> Mix.raise("Usage: mix playwright_ex.gen.api [--check] [<playwright-repo>]")
      end

    Mix.Task.run("compile")

    if opts[:check] do
      case check(repo) do
        [] -> Mix.shell().info("gen.api: up to date")
        stale -> Mix.raise("gen.api: out of date, run mix playwright_ex.gen.api: #{Enum.join(stale, ", ")}")
      end
    else
      files = sources(repo)
      for {path, source} <- files, File.read(path) != {:ok, source}, do: write(path, source)

      for path <- generated_files() -- Map.keys(files) do
        File.rm!(path)
        Mix.shell().info("Removed #{path}")
      end
    end
  end

  @doc false
  # Generated files that differ from what is on disk (or should not exist).
  def check(repo) do
    files = sources(repo)
    stale = for {path, source} <- files, File.read(path) != {:ok, source}, do: path
    stale ++ (generated_files() -- Map.keys(files))
  end

  defp generated_files do
    for path <- Path.wildcard(Path.join(@dir, "*.ex")), String.starts_with?(File.read!(path), @header), do: path
  end

  @doc false
  # `lang`: the client whose view of the docs to load ("js", "python" for the callback forms).
  def api_json(repo, lang \\ "js") do
    {node, _} = PlaywrightEx.Driver.ensure_installed()
    {json, 0} = System.cmd(node, ["-e", @load_api, Path.expand(repo), lang])
    JSON.decode!(json)
  end

  @doc false
  # %{path => source} for every class.
  def sources(repo) do
    api = api_json(repo)
    classes = ApiRules.apply(api, api_json(repo, "python"))

    ctx = %{
      classes: Map.new(classes, &{&1["name"], &1}),
      # Every upstream class, for links to playwright.dev.
      all: MapSet.new(api, & &1["name"])
    }

    Map.new(classes, fn class ->
      path = Path.join(@dir, Macro.underscore(class["name"]) <> ".ex")
      {path, format(class_source(Map.put(ctx, :class, class["name"]), class))}
    end)
  end

  # `Expect` (the assertion classes, see `Mix.PlaywrightEx.ApiRules`) is implemented by the matchers.
  defp impl("Expect"), do: PlaywrightEx.Matchers.Expect
  defp impl(class_name), do: Module.concat(PlaywrightEx.Client, class_name)
  defp facade(class_name), do: Module.concat(PlaywrightEx, class_name)

  # The matcher's function in `customAsyncMatchers`, with the JS arity (this, receiver, arguments).
  defp matcher_function(%{"matcher" => %{"name" => name}} = member) do
    fun = PlaywrightEx.Matchers.Expect.custom_async_matchers()[name]

    if !is_function(fun, 2 + length(member["args"])),
      do: Mix.raise("gen.api: matcher #{name} is missing from PlaywrightEx.Matchers.Expect.custom_async_matchers/0")

    fun
  end

  # --- modules -----------------------------------------------------------------

  defp class_source(ctx, class) do
    name = class["name"]
    members = class["members"] |> Enum.reject(&(&1["kind"] == "event")) |> Enum.uniq_by(& &1["alias"])
    events = for m <- class["members"], m["kind"] == "event", do: m
    receiver = receiver(name, members)
    listeners = if events != [], do: @listener_methods, else: []

    # `@events` maps event atoms to JS names, for listeners and `event` arguments (`wait_for_event`).
    events_table =
      if listeners != [] or Enum.any?(members, &event_arg?/1),
        do: "@events #{render({:map, Enum.map(events, &{event_atom(&1), String.downcase(&1["name"])})})}"

    handle_type =
      if name != "Expect",
        do: """
        @typedoc "A `#{name}` handle. Compare handles with `==`, their fields are internal."
        @type t :: #{struct_type(ctx, name)}
        """

    body = """
    #{handle_type}#{event_type(events)}

    #{events_table}

    #{Enum.map_join(members, "\n\n", &member_source(ctx, class, &1, receiver))}

    #{listeners_source(ctx, class, events, listeners, receiver)}
    """

    """
    #{@header}
    defmodule #{inspect(facade(name))} do
      #{String.replace(since(class), "@doc", "@moduledoc")}@moduledoc #{doc(module_doc(ctx, class, events))}

      #{if String.contains?(body, "Facade."), do: "alias PlaywrightEx.Runtime.Facade"}

      #{body}
    end
    """
  end

  # A subclass handle is one too (an `ElementHandle` is a `JSHandle`).
  defp struct_type(ctx, name) do
    subclasses = for {sub, %{"extends" => ^name}} <- ctx.classes, do: sub

    if Code.ensure_loaded?(impl(name)) and function_exported?(impl(name), :__struct__, 0),
      do: Enum.map_join([name | Enum.sort(subclasses)], " | ", &"%#{inspect(impl(&1))}{}"),
      else: "term()"
  end

  defp module_doc(ctx, class, events) do
    sections([
      md(class["spec"], ctx),
      class["extends"] && extends_doc(ctx, class["extends"]),
      events != [] &&
        "## Events\n\n" <>
          Enum.map_join(events, "\n\n", &event_doc(ctx, &1, class["since"]))
    ])
  end

  defp extends_doc(ctx, parent) do
    if Map.has_key?(ctx.classes, parent),
      do: "Extends `#{inspect(facade(parent))}`: its functions take this handle too.",
      else: "Extends `#{parent}`."
  end

  defp event_doc(ctx, event, since) do
    doc = md(event["spec"], ctx)
    doc = if newer?(event["since"], since), do: inline_join("*Since #{version(event["since"])}.*", doc), else: doc
    sections(["### `#{inspect(event_atom(event))}`", doc])
  end

  defp event_type([]), do: ""

  defp event_type(events),
    do: "@type event :: " <> Enum.map_join(events, " | ", &inspect(event_atom(&1)))

  # --- members -----------------------------------------------------------------

  # `to_have_text(locator, expected, options)`: `createMatcher(name, info, actual, matcher)(...args)`.
  defp member_source(ctx, class, %{"matcher" => matcher} = member, _receiver) do
    name = snake(member["alias"])
    api_name = api_name(class["name"], member["alias"])
    receiver = matcher_receiver(matcher["receivers"])
    vars = Enum.map(member["args"], &var(&1["name"]))
    attrs = for {arg, var} <- Enum.zip(member["args"], vars), schema = arg_schema(ctx, arg), do: {arg, var, schema}
    params = [receiver | Enum.map(Enum.zip(member["args"], vars), &param/1)]
    fun = matcher_function(member)
    info = Function.info(fun)
    capture = "&#{inspect(info[:module])}.#{info[:name]}/#{info[:arity]}"

    call =
      "#{inspect(impl(class["name"]))}.create_matcher(#{inspect(matcher["name"])}, %{isNot: #{matcher["isNot"]}}, " <>
        "#{receiver}, #{capture}).([#{Enum.join(vars, ", ")}])"

    receiver_spec = Enum.map_join(matcher["receivers"], " | ", &"#{inspect(facade(&1))}.t()")
    spec_args = Enum.join([receiver_spec | Enum.map(member["args"], &arg_spec(ctx, &1, name))], ", ")
    conversions = Enum.map_join(attrs, "\n", &conversion(name, api_name, &1))

    attributes =
      Enum.join(
        [
          Enum.map_join(attrs, "\n", &attribute(name, &1))
          | for(%{"name" => "options"} = arg <- member["args"], do: options_type(ctx, name, arg))
        ],
        "\n\n"
      )

    """
    #{attributes}

    #{since(member)}#{deprecated(member)}@doc #{doc(member_doc(ctx, member, member["args"]))}
    @spec #{name}(#{spec_args}) :: :ok | {:error, Exception.t()}
    def #{name}(#{Enum.join(params, ", ")}) do
      #{conversions}
      Facade.matcher(#{receiver}, fn -> #{call} end)
    end

    #{since(member)}#{deprecated(member)}@doc "Like `#{name}/#{length(params)}`, but raises `ExUnit.AssertionError` when the expectation is not met."
    @spec #{name}!(#{spec_args}) :: :ok
    def #{name}!(#{Enum.join(params, ", ")}) do
      #{conversions}
      Facade.matcher!(#{receiver}, fn -> #{call} end)
    end
    """
  end

  defp member_source(ctx, class, member, receiver) do
    name = snake(member["alias"])
    # A callback form (`expect_popup`) is named after the wait it starts (`page.waitForEvent`).
    callback = member["callback"]
    api_name = api_name(class["name"], if(callback, do: callback["call"], else: member["alias"]))
    args = if callback, do: with_action(member["args"]), else: member["args"]
    vars = Enum.map(args, &var(&1["name"]))
    attrs = for {arg, var} <- Enum.zip(args, vars), schema = arg_schema(ctx, arg), do: {arg, var, schema}
    params = [receiver | Enum.map(Enum.zip(args, vars), &param/1)]
    void? = get_in(member, ["type", "name"]) == "void"
    doc = member_doc(ctx, member, args)
    doc = if member["promise"], do: sections([doc, promise_doc(ctx, class, member, length(params))]), else: doc

    attributes =
      Enum.join(
        [
          Enum.map_join(attrs, "\n", &attribute(name, &1))
          | for(%{"name" => "options"} = arg <- args, do: options_type(ctx, name, arg))
        ],
        "\n\n"
      )

    member_def(member, %{
      name: name,
      api_name: inspect(api_name),
      receiver: receiver,
      params: params,
      head: "#{name}(#{Enum.join(params, ", ")})",
      attributes: attributes,
      conversions: Enum.map_join(attrs, "\n", &conversion(name, api_name, &1)),
      call: client_call(class, member, receiver, vars),
      void?: void?,
      spec_args: Enum.join(["t()" | Enum.map(args, &arg_spec(ctx, &1, name))], ", "),
      return: if(void?, do: ":ok", else: type_spec(ctx, member["type"], :out)),
      docs: since(member) <> deprecated(member) <> "@doc #{doc(doc)}"
    })
  end

  defp param({%{"name" => "options"}, var}), do: "#{var} \\\\ []"
  defp param({%{"required" => true}, var}), do: var
  defp param({_, var}), do: "#{var} \\\\ nil"

  defp attribute(_name, {_, _, :event}), do: ""
  defp attribute(name, {_, var, schema}), do: "@#{name}_#{var} #{render(schema)}"

  defp conversion(name, api_name, {%{"name" => "options"}, var, _}),
    do: "#{var} = Facade.options!(#{var}, @#{name}_#{var}, #{inspect(api_name)})"

  defp conversion(_name, api_name, {_, var, :event}),
    do: "#{var} = Facade.event!(#{var}, @events, #{inspect(api_name)})"

  defp conversion(name, api_name, {_, var, _}),
    do: "#{var} = Facade.arg!(#{var}, @#{name}_#{var}, #{inspect(api_name)})"

  defp client_call(class, %{"callback" => %{"call" => call, "event" => event}}, receiver, vars) do
    call_args = [receiver | List.wrap(event && inspect(event))] ++ (vars -- ["action"])
    "#{inspect(impl(class["name"]))}.#{snake(call)}(#{Enum.join(call_args, ", ")})"
  end

  defp client_call(class, member, receiver, vars),
    do: "#{inspect(impl(class["name"]))}.#{snake(member["alias"])}(#{Enum.join([receiver | vars], ", ")})"

  defp member_def(%{"promise" => promise}, m) when is_binary(promise) do
    """
    #{m.attributes}

    #{m.docs}
    @spec #{m.name}(#{m.spec_args}) :: PlaywrightEx.Promise.t()
    def #{m.head} do
      #{m.conversions}
      Facade.promise(#{m.api_name}, #{m.receiver}, fn -> #{m.call} end)
    end
    """
  end

  defp member_def(%{"async" => true} = member, m) do
    {async, async!, extra} =
      cond do
        member["callback"] -> {"expect", "expect!", ", action"}
        m.void? -> {"async_void", "async_void!", ""}
        true -> {"async", "async!", ""}
      end

    """
    #{m.attributes}

    #{m.docs}
    @spec #{m.name}(#{m.spec_args}) :: #{if m.void?, do: ":ok", else: "{:ok, #{m.return}}"} | {:error, Exception.t()}
    def #{m.head} do
      #{m.conversions}
      Facade.#{async}(#{m.api_name}, #{m.receiver}, fn -> #{m.call} end#{extra})
    end

    #{since(member)}#{deprecated(member)}@doc "Like `#{m.name}/#{length(m.params)}`, but returns the value and raises on error."
    @spec #{m.name}!(#{m.spec_args}) :: #{m.return}
    def #{m.name}!(#{Enum.join(m.params, ", ")}) do
      #{m.conversions}
      Facade.#{async!}(#{m.api_name}, #{m.receiver}, fn -> #{m.call} end#{extra})
    end
    """
  end

  defp member_def(_member, m) do
    """
    #{m.attributes}

    #{m.docs}
    @spec #{m.name}(#{m.spec_args}) :: #{m.return}
    def #{m.head} do
      #{m.conversions}
      #{m.call}#{if m.void?, do: "\n:ok"}
    end
    """
  end

  # The `action` of a callback form, before the options (C#'s `RunAndWaitForPopupAsync(action, options)`).
  defp with_action(args) do
    action = %{
      "name" => "action",
      "required" => true,
      "type" => %{"name" => "function", "args" => []},
      "spec" => [
        %{
          "type" => "text",
          "text" =>
            "A function that performs the action triggering the wait. It runs once the wait is set up; " <>
              "its result is ignored and what it raises propagates."
        }
      ]
    }

    {options, positional} = Enum.split_with(args, &(&1["name"] == "options"))
    positional ++ [action | options]
  end

  defp promise_doc(_ctx, class, member, arity) do
    callback =
      if Enum.any?(class["members"], &(&1["alias"] == member["promise"])),
        do: " The callback form is `#{member["promise"]}/#{arity + 1}`.",
        else: ""

    "Returns a `PlaywrightEx.Promise` at once: the wait is set up before it returns, as JS starts it " <>
      "without `await`. Await it with `PlaywrightEx.Promise.await/1`." <> callback
  end

  defp event_arg?(member), do: Enum.any?(member["args"], &event_arg_type?/1)

  defp event_arg_type?(%{"name" => "event", "type" => %{"name" => "string"}}), do: true
  defp event_arg_type?(_arg), do: false

  defp member_doc(ctx, member, args) do
    positional = for arg <- args, arg["name"] != "options", arg["spec"] != [] or props(arg["type"]) != [], do: arg
    options = for arg <- args, arg["name"] == "options", p <- arg["type"]["properties"], do: p

    sections([
      md(member["spec"], ctx),
      member["discouraged"] && note("Discouraged", "warning", text(member["discouraged"], ctx)),
      positional != [] &&
        "## Arguments\n\n" <>
          Enum.map_join(positional, "\n", &bullet(ctx, "`#{var(&1["name"])}`", &1, member["since"])),
      options != [] && "## Options\n\n" <> Enum.map_join(options, "\n", &option_bullet(ctx, &1, member["since"]))
    ])
  end

  defp option_bullet(ctx, prop, since), do: bullet(ctx, "`#{inspect(atom(prop["name"]))}`", prop, since)
  defp field_bullet(ctx, prop, since), do: bullet(ctx, "`#{inspect(String.to_atom(prop["name"]))}`", prop, since)

  # "* name - doc", then the fields of an object type as nested bullets. Fields newer than
  # their parent say since when, as on playwright.dev.
  defp bullet(ctx, name, prop, since) do
    doc = md(prop["spec"], ctx)
    doc = if newer?(prop["since"], since), do: inline_join("*Since #{version(prop["since"])}.*", doc), else: doc

    item =
      cond do
        doc == "" -> "* #{name}"
        block_start?(doc) -> "* #{name}\n\n" <> indent(doc, 2)
        true -> "* #{name} - " <> indent(doc, 2, :hanging)
      end

    case props(prop["type"]) do
      [] ->
        item

      fields ->
        separator = if item =~ "\n\n", do: "\n\n", else: "\n"
        item <> separator <> indent(Enum.map_join(fields, "\n", &field_bullet(ctx, &1, prop["since"])), 2)
    end
  end

  defp block_start?(doc), do: doc =~ ~r/^(```|> |\* |- |\||\d+\. )/

  defp inline_join(head, ""), do: head
  defp inline_join(head, doc), do: if(block_start?(doc), do: head <> "\n\n" <> doc, else: head <> " " <> doc)

  # api.json versions are "v1.8"; ours mirror upstream's (see PLAN.md).
  defp version("v" <> version), do: version

  defp newer?(since, parent) when is_binary(since) and is_binary(parent),
    do: Version.compare(semver(since), semver(parent)) == :gt

  defp newer?(_since, _parent), do: false

  defp semver(since), do: since |> version() |> Kernel.<>(".0") |> Version.parse!()

  defp since(%{"since" => since}) when is_binary(since), do: "@doc since: #{inspect(version(since))}\n"
  defp since(_member), do: ""

  # Fields of an object type, also inside arrays and unions (`viewport: null|Object`).
  defp props(%{"properties" => props}) when is_list(props), do: Enum.uniq_by(props, & &1["name"])
  defp props(%{"name" => "Array", "templates" => [item]}), do: props(item)
  defp props(%{"union" => union}) when is_list(union), do: Enum.find_value(union, [], &(props(&1) != [] && props(&1)))
  defp props(_type), do: []

  defp deprecated(%{"deprecated" => text}) when is_binary(text),
    do: "@doc deprecated: #{inspect(first_line(String.replace(text, "↵", " ")))}\n"

  defp deprecated(_member), do: ""

  defp listeners_source(_ctx, _class, _events, [], _receiver), do: ""

  # One spec per event, as the overloads in upstream's types.d.ts.
  defp listeners_source(ctx, class, events, listeners, receiver) do
    Enum.map_join(listeners, "\n\n", fn method ->
      name = snake(method)
      api_name = api_name(class["name"], method)

      doc =
        case method do
          m when m in ~w(off removeListener) -> "Removes an event listener added by `on/3` or `add_listener/3`."
          "once" -> "Adds an event listener that is removed after it is triggered once. See `on/3`."
          _ -> "Adds an event listener for `event`, see the module docs for the events."
        end

      """
      @doc #{inspect(doc)}
      @doc group: "Events"
      #{Enum.map_join(events, "\n", &listener_spec(ctx, name, &1))}#{if class["openEvents"], do: "\n@spec #{name}(t(), String.t(), (term() -> term())) :: t()"}
      def #{name}(#{receiver}, event, listener),
        do: #{inspect(impl(class["name"]))}.#{name}(#{receiver}, Facade.event!(event, @events, #{inspect(api_name)}#{if class["openEvents"], do: ", true"}), listener)
      """
    end)
  end

  defp listener_spec(ctx, name, event) do
    payload = if event["type"], do: type_spec(ctx, event["type"], :out), else: "nil"
    "@spec #{name}(t(), #{inspect(event_atom(event))}, (#{payload} -> term())) :: t()"
  end

  # --- types ---------------------------------------------------------------------

  # Schemas keep api.json order: `{:map, pairs}` is written as a map literal in that order.
  # A positional `timeout` accepts `:infinity`, as the `timeout:` option does.
  # Options have snake_case keys and atom enums; nested objects are JS values (`{:fields, _}`,
  # JS keys, only checked), as in the Python client.
  defp arg_schema(_ctx, %{"name" => "timeout"}), do: :timeout
  defp arg_schema(_ctx, %{"name" => "event", "type" => %{"name" => "string"}}), do: :event

  defp arg_schema(ctx, %{"name" => "options", "type" => %{"properties" => props}}) do
    pairs =
      for prop <- Enum.uniq_by(props, & &1["name"]),
          do: {atom(prop["name"]), {String.to_atom(prop["name"]), schema(ctx, prop["type"], :value)}}

    {:object, {:map, pairs}}
  end

  defp arg_schema(ctx, arg), do: schema(ctx, arg["type"], :value)

  defp schema(_ctx, nil, _mode), do: nil

  defp schema(ctx, %{"union" => union}, mode) when is_list(union) do
    {literals, others} = Enum.split_with(union, &literal?(&1["name"]))
    literals = for %{"name" => n} <- literals, n not in ["null", "undefined"], uniq: true, do: literal(n)
    schemas = Enum.flat_map(others, &List.wrap(schema(ctx, &1, mode)))
    schemas = if literals == [] or mode == :nested, do: schemas, else: [{:enum, {:map, literals}} | schemas]

    case schemas do
      [] -> nil
      [one] -> one
      many -> {:union, many}
    end
  end

  # A dictionary (`Object<string, ...>`): its keys are data, not checked. api.json can attach the
  # properties of an object value to it (`multipart`).
  defp schema(_ctx, %{"name" => "Object", "templates" => [_, _]}, _mode), do: nil

  # An open object (a storage state, see `Mix.PlaywrightEx.ApiRules`): passed as it is.
  defp schema(_ctx, %{"open" => true}, _mode), do: nil

  defp schema(ctx, %{"properties" => props}, _mode) when is_list(props) and props != [] do
    pairs =
      for prop <- Enum.uniq_by(props, & &1["name"]),
          do: {String.to_atom(prop["name"]), schema(ctx, prop["type"], :nested)}

    {:fields, {:map, pairs}}
  end

  defp schema(ctx, %{"name" => "Array", "templates" => [item]}, mode) do
    if s = schema(ctx, item, mode), do: {:array, s}
  end

  defp schema(_ctx, %{"name" => name}, :value) do
    if literal?(name) and name not in ["null", "undefined"], do: {:enum, {:map, [literal(name)]}}
  end

  defp schema(_ctx, _type, :nested), do: nil

  defp literal?(name), do: String.starts_with?(name, "\"") or name in ["null", "undefined"]

  defp literal(quoted) do
    value = String.trim(quoted, "\"")
    {value |> String.replace("-", "_") |> Macro.underscore() |> String.to_atom(), value}
  end

  # Exceptions by JS class name.
  @errors %{"TimeoutError" => PlaywrightEx.Client.Errors.TimeoutError}

  @simple %{
    "string" => "String.t()",
    "path" => "String.t()",
    "URL" => "String.t()",
    "boolean" => "boolean()",
    "int" => "integer()",
    "long" => "integer()",
    "bigint" => "integer()",
    "float" => "number()",
    "number" => "number()",
    "Buffer" => "binary()",
    # Node's `Readable`: the client returns an `Enumerable` of binary chunks.
    "Readable" => "Enumerable.t(binary())",
    "RegExp" => "Regex.t()",
    "Date" => "DateTime.t()",
    "Error" => "Exception.t()",
    "function" => "fun()",
    "Function" => "fun()",
    "null" => ":null",
    "undefined" => "nil",
    "void" => "nil"
  }

  # Inputs as the facade takes them (snake_case keys, enums as atoms), outputs as the client
  # returns them (JS keys, enums as strings).
  defp arg_spec(_ctx, %{"name" => "options"}, name), do: "#{name}_options()"

  defp arg_spec(_ctx, %{"name" => "event", "type" => %{"name" => "string"}} = arg, _name),
    do: nullable(arg, "event() | String.t()")

  defp arg_spec(ctx, arg, _name), do: nullable(arg, prop_spec(ctx, arg))

  defp nullable(%{"required" => false}, spec), do: "#{spec} | nil"
  defp nullable(_arg, spec), do: spec

  defp prop_spec(_ctx, %{"name" => "timeout"}), do: "number() | :infinity"
  defp prop_spec(ctx, prop), do: type_spec(ctx, prop["type"], :in)

  defp options_type(ctx, name, arg) do
    props = Enum.uniq_by(arg["type"]["properties"], & &1["name"])
    keyword = Enum.map_join(props, ", ", &"#{key(atom(&1["name"]))} #{prop_spec(ctx, &1)}")
    map = Enum.map_join(props, ", ", &"optional(#{inspect(atom(&1["name"]))}) => #{prop_spec(ctx, &1)}")

    """
    @typedoc "Options of `#{name}`, see its docs."
    @type #{name}_options :: [#{keyword}] | %{#{map}}
    """
  end

  defp type_spec(_ctx, nil, _dir), do: "term()"

  # `string|Buffer`: JS branches on Buffer, a Buffer is `{:binary, bytes}` (PLAN, Decisions).
  defp type_spec(ctx, %{"union" => union}, dir) when is_list(union) do
    string_or_buffer? = Enum.any?(union, &(&1["name"] == "string")) and Enum.any?(union, &(&1["name"] == "Buffer"))

    union
    |> Enum.map(
      &if(string_or_buffer? and &1["name"] == "Buffer", do: "{:binary, binary()}", else: type_spec(ctx, &1, dir))
    )
    |> Enum.uniq()
    |> Enum.join(" | ")
  end

  defp type_spec(ctx, %{"name" => "Object", "templates" => [key, value]}, dir),
    do: "%{optional(#{type_spec(ctx, key, dir)}) => #{type_spec(ctx, value, dir)}}"

  # Objects are JS values both ways: results as the client returns them, inputs (nested in
  # options or positional) passed as they are, so a result can be passed back.
  defp type_spec(ctx, %{"properties" => props} = type, dir) when is_list(props) and props != [],
    do: object_spec(ctx, Enum.uniq_by(props, & &1["name"]), if(dir == :out, do: :out, else: :nested), type["open"])

  # `X | null` results are `nil` (`from_nullable`); `:null` is a JS value passed in.
  defp type_spec(_ctx, %{"name" => "null"}, :out), do: "nil"
  defp type_spec(_ctx, %{"name" => "\"" <> _}, dir) when dir in [:out, :nested], do: "String.t()"
  defp type_spec(ctx, %{"name" => "Array", "templates" => [item]}, dir), do: "[#{type_spec(ctx, item, dir)}]"

  defp type_spec(_ctx, %{"name" => "Object"}, _dir), do: "map()"
  defp type_spec(ctx, %{"name" => "Promise", "templates" => [value]}, dir), do: type_spec(ctx, value, dir)

  # `typeof TimeoutError` (`playwright.errors`): the exception module.
  defp type_spec(_ctx, %{"name" => "typeof", "templates" => [%{"name" => name}]}, _dir),
    do: inspect(Map.fetch!(@errors, name))

  # A callback: Playwright passes the arguments (outputs) and takes the result (an input).
  defp type_spec(ctx, %{"name" => "function", "args" => args} = fun, _dir) when is_list(args) do
    result =
      case fun["returnType"] do
        %{"name" => name} when name in ["void", "any", "Promise"] -> "term()"
        nil -> "term()"
        type -> type_spec(ctx, type, :in)
      end

    "(#{Enum.map_join(args, ", ", &type_spec(ctx, &1, :out))} -> #{result})"
  end

  defp type_spec(ctx, %{"name" => name}, _dir) do
    cond do
      Map.has_key?(@simple, name) -> @simple[name]
      String.starts_with?(name, "\"") -> inspect(elem(literal(name), 0))
      Map.has_key?(ctx.classes, name) -> "#{inspect(facade(name))}.t()"
      true -> "term()"
    end
  end

  # JS keys, `%{width: number(), height: number()}`.
  # An open object has more fields than documented: `optional(atom()) => term()`.
  defp object_spec(ctx, props, dir, open?) do
    fields = for p <- props, do: {p["required"], String.to_atom(p["name"]), type_spec(ctx, p["type"], dir)}

    cond do
      open? -> "%{#{Enum.map_join(fields, ", ", &map_field/1)}, optional(atom()) => term()}"
      Enum.all?(fields, &elem(&1, 0)) -> "%{#{Enum.map_join(fields, ", ", fn {_, k, t} -> "#{key(k)} #{t}" end)}}"
      true -> "%{#{Enum.map_join(fields, ", ", &map_field/1)}}"
    end
  end

  defp map_field({true, key, type}), do: "required(#{inspect(key)}) => #{type}"
  defp map_field({_, key, type}), do: "optional(#{inspect(key)}) => #{type}"

  # --- names and docs --------------------------------------------------------------

  # clientStackTrace.ts normalizeAPIName: "APIRequestContext" -> "apiRequestContext".
  defp api_name(class_name, member) do
    [_, head, rest] = Regex.run(~r/^(API|JS|CDP|[A-Z])(.*)$/, class_name)
    "#{String.downcase(head)}#{rest}.#{member}"
  end

  defp matcher_receiver(receivers), do: receivers |> Enum.map_join("_or_", &snake/1)

  defp receiver(class_name, members) do
    receiver = snake(class_name)
    taken = for m <- members, a <- m["args"], do: var(a["name"])
    if receiver in taken, do: "this", else: receiver
  end

  defp event_atom(event), do: atom(event["name"])

  defp atom(js_name), do: js_name |> Macro.underscore() |> String.to_atom()

  # Names that are no Elixir function names: Python's (`eval_on_selector`, `and_`).
  @renamed %{
    "$" => "query_selector",
    "$$" => "query_selector_all",
    "$eval" => "eval_on_selector",
    "$$eval" => "eval_on_selector_all",
    "and" => "and_",
    "or" => "or_"
  }

  defp snake(js_name), do: Map.get_lazy(@renamed, js_name, fn -> Macro.underscore(js_name) end)

  defp var(js_name) do
    name = snake(js_name)
    if name in @reserved, do: name <> "_", else: name
  end

  defp first_line(text), do: text |> String.split("\n") |> hd()

  # --- docs: rendered from the `spec` markdown AST (upstream utils/markdown.js) ---------

  # Code blocks for other clients (`python async`, `java`, ...) are dropped.
  @foreign_langs ~w(java csharp cs python py)

  defp md(nil, _ctx), do: ""

  defp md(nodes, ctx) do
    nodes
    |> Enum.flat_map(&block(&1, ctx))
    |> Enum.chunk_while(
      nil,
      fn
        {kind, text}, {kind, acc} when kind in [:li, :table, :quote, :link_def] -> {:cont, {kind, acc <> "\n" <> text}}
        block, nil -> {:cont, block}
        block, acc -> {:cont, elem(acc, 1), block}
      end,
      fn
        nil -> {:cont, nil}
        acc -> {:cont, elem(acc, 1), nil}
      end
    )
    |> Enum.join("\n\n")
  end

  defp block(%{"type" => "text", "text" => text}, ctx) do
    kind =
      cond do
        String.starts_with?(text, "|") -> :table
        String.starts_with?(text, ">") -> :quote
        text =~ ~r/^\[[^\]]+\]:/ -> :link_def
        true -> :text
      end

    [{kind, text(text, ctx)}]
  end

  defp block(%{"type" => "code", "codeLang" => lang, "lines" => lines} = node, _ctx) do
    lang = lang |> String.split() |> hd()
    title = if node["title"], do: ["// #{node["title"]}"], else: []
    if lang in @foreign_langs, do: [], else: [{:code, Enum.join(["```#{lang}"] ++ title ++ lines ++ ["```"], "\n")}]
  end

  # `:::warning[Discouraged]` as an ExDoc admonition.
  defp block(%{"type" => "note", "noteType" => type} = node, ctx) do
    [_, kind | title] = Regex.run(~r/^(\w+)(?:\[(.*)\])?$/, type)
    class = Map.get(%{"note" => "info", "caution" => "warning", "danger" => "error"}, kind, kind)
    [{:note, note(Enum.at(title, 0, String.capitalize(kind)), class, md(node["children"], ctx))}]
  end

  defp block(%{"type" => "li", "liType" => type, "text" => text} = node, ctx) do
    marker = Map.fetch!(%{"bullet" => "*", "default" => "-", "ordinal" => "1."}, type)
    item = indent("#{marker} #{text(text, ctx)}", String.length(marker) + 1, :hanging)

    case md(node["children"], ctx) do
      "" -> [{:li, item}]
      children -> [{:li, item <> "\n" <> indent(children, String.length(marker) + 1)}]
    end
  end

  defp note(title, class, body), do: indent("#### #{title} {: .#{class}}\n\n#{body}", "> ")

  # Member refs (`[method: Page.goto]`), markdown links, inline code and raw type refs
  # (`[Promise]`), in one pass so that code and link texts are left alone.
  @inline ~r/\[`(method|property|event): (\w+)\.(\w+)(?:#\w+)?`\]|\[([^\]]*)\]\(([^)]*)\)|`([^`]+)`|\[([A-Za-z]\w*)\]/

  # Upstream joins the lines of a paragraph with `↵` (soft line breaks).
  defp text(text, ctx) do
    text
    |> String.replace("↵", "\n")
    |> then(
      &Regex.replace(@inline, &1, fn match, kind, class, member, label, href, code, type ->
        inline(ctx, match, {kind, class, member}, {label, href}, code, type)
      end)
    )
  end

  defp inline(ctx, _match, {kind, class, member}, _link, _code, _type) when kind != "",
    do: member_link(ctx, kind, class, member)

  defp inline(ctx, _match, _ref, {label, href}, _code, _type) when href != "", do: "[#{label}](#{href(ctx, href)})"
  defp inline(ctx, match, _ref, _link, code, "") when code != "", do: code_link(ctx, code) || match

  # `[Promise]`, `[string]`; not `[contenteditable]`.
  defp inline(ctx, match, _ref, _link, _code, type),
    do: code_link(ctx, type) || if(type =~ ~r/^[A-Z]|^string$/, do: "`#{type}`", else: match)

  # A facade function where generated, else playwright.dev (`linkUtils.js` createMarkdownLink).
  defp member_link(ctx, "event", class, event) do
    label = "`#{class}.on(#{inspect(atom(event))})`"

    if Map.has_key?(ctx.classes, class),
      do: "[#{label}](#{inspect(facade(class))}.html#module-#{atom(event)})",
      else: "[#{label}](#{dev_url(class)}##{kebab(class)}-event-#{kebab(event)})"
  end

  defp member_link(ctx, _kind, class, member) do
    with %{} = c <- ctx.classes[class],
         %{} = m <- Enum.find(c["members"], &(&1["alias"] == member and &1["kind"] != "event")) do
      "`#{inspect(facade(class))}.#{snake(member)}/#{1 + length(m["args"])}`"
    else
      _ -> "[`#{class}.#{member}`](#{dev_url(class)}##{kebab(class)}-#{kebab(member)})"
    end
  end

  # A class name in code (`Browser`), or an error class (`TimeoutError`).
  defp code_link(ctx, name) do
    cond do
      Map.has_key?(@errors, name) -> "[`#{name}`](`#{inspect(@errors[name])}`)"
      Map.has_key?(ctx.classes, name) -> "[`#{name}`](`#{inspect(facade(name))}`)"
      name in ctx.all -> "[`#{name}`](#{dev_url(name)})"
      true -> nil
    end
  end

  # Links relative to docs/src/api/ (with or without `.md`) as playwright.dev URLs.
  defp href(ctx, href) do
    case Regex.run(~r/^(\.\.\/|\.\/)?([\w\/-]*?)(?:\.md)?(#[\w-]*)?$/, href) do
      [_, "", "" | anchor] ->
        "#{dev_url(ctx.class)}#{anchor}"

      [_, "../", page | anchor] ->
        "https://playwright.dev/docs/#{page}#{anchor}"

      [_, _, "class-" <> name = page | anchor] ->
        class_href(ctx, name, anchor) || "https://playwright.dev/docs/api/#{page}#{anchor}"

      [_, _, page | anchor] ->
        "https://playwright.dev/docs/api/#{page}#{anchor}"

      nil ->
        href
    end
  end

  defp class_href(ctx, lower, []) do
    case Enum.find(Map.keys(ctx.classes), &(String.downcase(&1) == lower)) do
      nil -> nil
      class -> "`#{inspect(facade(class))}`"
    end
  end

  defp class_href(_ctx, _lower, _anchor), do: nil

  defp dev_url(class), do: "https://playwright.dev/docs/api/class-#{String.downcase(class)}"

  # lodash kebabCase: "waitForURL" -> "wait-for-url".
  defp kebab(name), do: name |> Macro.underscore() |> String.replace("_", "-")

  defp sections(parts), do: parts |> Enum.filter(&(is_binary(&1) and &1 != "")) |> Enum.join("\n\n")

  defp indent(text, n, mode \\ :all)
  defp indent(text, n, mode) when is_integer(n), do: indent(text, String.duplicate(" ", n), mode)

  defp indent(text, prefix, mode) do
    [first | rest] = String.split(text, "\n")
    prefixed = Enum.map(rest, &if(&1 == "", do: String.trim_trailing(prefix), else: prefix <> &1))
    Enum.join([if(mode == :hanging, do: first, else: prefix <> first) | prefixed], "\n")
  end

  defp doc(""), do: inspect("")

  defp doc(text) do
    if String.contains?(text, ~s(""")), do: inspect(text), else: ~s(~S"""\n#{text}\n""")
  end

  # Not `inspect/1`: it orders small atom-keyed maps by atom table position, which depends on
  # what the VM loaded before.
  defp render({:map, pairs}), do: "%{#{Enum.map_join(pairs, ", ", fn {k, v} -> "#{key(k)} #{render(v)}" end)}}"

  defp render(tuple) when is_tuple(tuple), do: "{#{tuple |> Tuple.to_list() |> Enum.map_join(", ", &render/1)}}"
  defp render(list) when is_list(list), do: "[#{Enum.map_join(list, ", ", &render/1)}]"
  defp render(term), do: inspect(term)

  defp key(atom), do: String.trim_leading(inspect(atom), ":") <> ":"

  defp format(source), do: IO.iodata_to_binary([Code.format_string!(source, line_length: 120), "\n"])

  defp write(path, source) do
    File.mkdir_p!(Path.dirname(path))
    File.write!(path, source)
    Mix.shell().info("Wrote #{path}")
  end
end

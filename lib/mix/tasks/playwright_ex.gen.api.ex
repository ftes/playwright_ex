defmodule Mix.Tasks.PlaywrightEx.Gen.Api do
  @shortdoc "Generates the public API facade from upstream api.json"
  @moduledoc """
  Generates the public API (`PlaywrightEx.Browser`, ...) from upstream's `api.json`.

      mix playwright_ex.gen.api [--check] [<playwright-repo>]

  `<playwright-repo>` is a checkout of microsoft/playwright at the pinned driver version, by
  default `PlaywrightEx.Upstream.ensure!/0`. `api.json` is built from its `docs/src/api` with
  upstream `utils/doclint/generateApiJson.js`, filtered to `langs: js` with upstream's own
  `filterForLanguage`, using the installed driver's Node (no npm install). Then
  `Mix.PlaywrightEx.ApiRules` applies the Elixir rules.

  Writes `lib/playwright_ex/api/<class>.ex` for every class whose `PlaywrightEx.Client.<Class>`
  is ported. A member is generated when the client exports it with the JS arity (receiver
  plus JS arguments), so regenerate after porting a method; the others are listed in the
  moduledoc as not ported. Each function sets the API name for errors, converts options
  (`PlaywrightEx.Runtime.Facade`), carries docs and specs, and calls the client directly, so a
  client function that disappears is a compile warning.

    * `async: true` members: `name/n` returns `{:ok, value} | {:error, exception}` (`:ok` for
      `void`), `name!/n` returns the value or raises.
    * `async: false` members and properties: plain values, called without the baton.
    * Classes with events: `on/3`, `once/3`, `add_listener/3`, `remove_listener/3`, `off/3`,
      `prepend_listener/3` with event atoms (`:disconnected`), as `types.d.ts` has them.

  `--check` writes nothing and fails if a file is out of date (`mix playwright_ex.parity` runs it).
  """
  use Mix.Task

  alias Mix.PlaywrightEx.ApiRules

  @dir "lib/playwright_ex/api"
  @header "# This file is generated by `mix playwright_ex.gen.api` from api.json, do not edit manually.\n"
  @listener_methods ~w(on once addListener removeListener off prependListener)
  @reserved ~w(after and catch do else end false fn in nil not or rescue true when)

  # api.json for the JS client: generateApiJson.js after `documentation.filterForLanguage('js')`.
  # linkUtils.js requires lodash/kebabCase, inlined here.
  @load_api """
  const path = require('path');
  const Module = require('module');
  const repo = process.argv[1];
  const load = Module._load;
  Module._load = function (request, ...rest) {
    if (request === 'lodash/kebabCase.js' || request === 'lodash/kebabCase')
      return s => s.replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[^A-Za-z0-9]+/).filter(Boolean).join('-').toLowerCase();
    return load.call(this, request, ...rest);
  };
  const apiParser = require(path.join(repo, 'utils', 'doclint', 'api_parser.js'));
  const parseApi = apiParser.parseApi;
  apiParser.parseApi = (...args) => {
    const documentation = parseApi(...args);
    documentation.filterForLanguage('js');
    return documentation;
  };
  require(path.join(repo, 'utils', 'doclint', 'generateApiJson.js'));
  """

  @impl Mix.Task
  def run(argv) do
    {opts, args} = OptionParser.parse!(argv, strict: [check: :boolean])

    repo =
      case args do
        [] -> PlaywrightEx.Upstream.ensure!()
        [repo] -> repo
        _ -> Mix.raise("Usage: mix playwright_ex.gen.api [--check] [<playwright-repo>]")
      end

    Mix.Task.run("compile")

    if opts[:check] do
      case check(repo) do
        [] -> Mix.shell().info("gen.api: up to date")
        stale -> Mix.raise("gen.api: out of date, run mix playwright_ex.gen.api: #{Enum.join(stale, ", ")}")
      end
    else
      files = sources(repo)
      for {path, source} <- files, File.read(path) != {:ok, source}, do: write(path, source)

      for path <- generated_files() -- Map.keys(files) do
        File.rm!(path)
        Mix.shell().info("Removed #{path}")
      end
    end
  end

  @doc false
  # Generated files that differ from what is on disk (or should not exist).
  def check(repo) do
    files = sources(repo)
    stale = for {path, source} <- files, File.read(path) != {:ok, source}, do: path
    stale ++ (generated_files() -- Map.keys(files))
  end

  defp generated_files do
    for path <- Path.wildcard(Path.join(@dir, "*.ex")), String.starts_with?(File.read!(path), @header), do: path
  end

  @doc false
  def api_json(repo) do
    {node, _} = PlaywrightEx.Driver.ensure_installed()
    {json, 0} = System.cmd(node, ["-e", @load_api, Path.expand(repo)])
    JSON.decode!(json)
  end

  @doc false
  # %{path => source} for every ported class.
  def sources(repo) do
    classes = repo |> api_json() |> ApiRules.apply() |> Enum.filter(&Code.ensure_loaded?(impl(&1["name"])))
    ctx = %{classes: Map.new(classes, &{&1["name"], &1}), exported: Map.new(classes, &{&1["name"], exported(&1)})}

    Map.new(classes, fn class ->
      path = Path.join(@dir, Macro.underscore(class["name"]) <> ".ex")
      {path, format(class_source(ctx, class))}
    end)
  end

  defp impl(class_name), do: Module.concat(PlaywrightEx.Client, class_name)
  defp facade(class_name), do: Module.concat(PlaywrightEx, class_name)

  # Members of `class` the client implements, by alias.
  defp exported(class) do
    impl = impl(class["name"])

    for member <- class["members"],
        member["kind"] in ["method", "property"],
        function_exported?(impl, String.to_atom(snake(member["alias"])), 1 + length(member["args"])),
        into: MapSet.new(),
        do: member["alias"]
  end

  # --- modules -----------------------------------------------------------------

  defp class_source(ctx, class) do
    name = class["name"]
    exported = ctx.exported[name]
    members = class["members"] |> Enum.reject(&(&1["kind"] == "event")) |> Enum.uniq_by(& &1["alias"])
    {ported, unported} = Enum.split_with(members, &(&1["alias"] in exported))
    events = for m <- class["members"], m["kind"] == "event", do: m
    receiver = receiver(name, ported)

    listeners =
      for method <- @listener_methods,
          events != [],
          function_exported?(impl(name), String.to_atom(snake(method)), 3),
          do: method

    body = """
    @typedoc "A `#{name}` handle. Compare handles with `==`, their fields are internal."
    @opaque t :: #{struct_type(name)}
    #{event_type(events)}

    #{Enum.map_join(ported, "\n\n", &member_source(ctx, class, &1, receiver))}

    #{listeners_source(class, events, listeners, receiver)}
    """

    """
    #{@header}
    defmodule #{inspect(facade(name))} do
      @moduledoc #{doc(module_doc(ctx, class, events, unported))}

      #{if String.contains?(body, "Facade."), do: "alias PlaywrightEx.Runtime.Facade"}

      #{body}
    end
    """
  end

  defp struct_type(name) do
    if function_exported?(impl(name), :__struct__, 0), do: "%#{inspect(impl(name))}{}", else: "term()"
  end

  defp module_doc(ctx, class, events, unported) do
    parts = [
      class["comment"],
      class["extends"] && "Extends `#{class["extends"]}`.",
      events != [] &&
        "## Events\n\n" <>
          Enum.map_join(events, "\n", fn e -> "  * `#{inspect(event_atom(e))}`" <> bullet(e["comment"]) end),
      unported != [] &&
        "Not ported yet: " <> Enum.map_join(unported, ", ", &"`#{&1["alias"]}`") <> "."
    ]

    parts |> Enum.filter(&(is_binary(&1) and &1 != "")) |> Enum.join("\n\n") |> comment(ctx)
  end

  defp event_type([]), do: ""

  defp event_type(events),
    do: "@type event :: " <> Enum.map_join(events, " | ", &inspect(event_atom(&1)))

  # --- members -----------------------------------------------------------------

  defp member_source(ctx, class, member, receiver) do
    name = snake(member["alias"])
    api_name = api_name(class["name"], member["alias"])
    args = member["args"]
    vars = Enum.map(args, &var(&1["name"]))
    attrs = for {arg, var} <- Enum.zip(args, vars), schema = arg_schema(ctx, arg), do: {arg, var, schema}

    params =
      [receiver] ++
        Enum.map(Enum.zip(args, vars), fn
          {%{"name" => "options"}, var} -> "#{var} \\\\ []"
          {%{"required" => true}, var} -> var
          {_, var} -> "#{var} \\\\ nil"
        end)

    conversions =
      Enum.map_join(attrs, "\n", fn
        {%{"name" => "options"}, var, _} -> "#{var} = Facade.options!(#{var}, @#{name}_#{var}, #{inspect(api_name)})"
        {_, var, _} -> "#{var} = Facade.arg!(#{var}, @#{name}_#{var}, #{inspect(api_name)})"
      end)

    attributes =
      Enum.map_join(attrs, "\n", fn {_, var, schema} -> "@#{name}_#{var} #{render(schema)}" end)

    call = "#{inspect(impl(class["name"]))}.#{name}(#{Enum.join([receiver | vars], ", ")})"
    void? = get_in(member, ["type", "name"]) == "void"
    head = "#{name}(#{Enum.join(params, ", ")})"
    spec_args = Enum.join(["t()" | Enum.map(args, &spec(ctx, &1["type"], :in, &1))], ", ")
    return = if void?, do: ":ok", else: spec(ctx, member["type"], :out, nil)
    docs = deprecated(member) <> "@doc #{doc(member_doc(ctx, member, args))}"

    if member["async"] do
      fun = "fn -> #{call} end"
      {async, async!} = if void?, do: {"async_void", "async_void!"}, else: {"async", "async!"}

      """
      #{attributes}

      #{docs}
      @spec #{name}(#{spec_args}) :: #{if void?, do: ":ok", else: "{:ok, #{return}}"} | {:error, Exception.t()}
      def #{head} do
        #{conversions}
        Facade.#{async}(#{inspect(api_name)}, #{receiver}, #{fun})
      end

      #{deprecated(member)}@doc "Like `#{name}/#{length(params)}`, but returns the value and raises on error."
      @spec #{name}!(#{spec_args}) :: #{return}
      def #{name}!(#{Enum.join(params, ", ")}) do
        #{conversions}
        Facade.#{async!}(#{inspect(api_name)}, #{receiver}, #{fun})
      end
      """
    else
      """
      #{attributes}

      #{docs}
      @spec #{name}(#{spec_args}) :: #{return}
      def #{head} do
        #{conversions}
        #{call}
      end
      """
    end
  end

  defp member_doc(ctx, member, args) do
    positional = for arg <- args, arg["name"] != "options", arg["comment"] not in [nil, ""], do: arg
    options = for arg <- args, arg["name"] == "options", p <- arg["type"]["properties"], do: p

    [
      member["comment"],
      member["discouraged"] && "Discouraged: " <> member["discouraged"],
      positional != [] &&
        "## Arguments\n\n" <>
          Enum.map_join(positional, "\n", &"  * `#{var(&1["name"])}`#{bullet(&1["comment"])}"),
      options != [] &&
        "## Options\n\n" <>
          Enum.map_join(options, "\n", &"  * `#{inspect(atom(&1["name"]))}`#{bullet(&1["comment"])}")
    ]
    |> Enum.filter(&(is_binary(&1) and &1 != ""))
    |> Enum.join("\n\n")
    |> comment(ctx)
  end

  defp deprecated(%{"deprecated" => text}) when is_binary(text), do: "@doc deprecated: #{inspect(first_line(text))}\n"
  defp deprecated(_member), do: ""

  defp listeners_source(_class, _events, [], _receiver), do: ""

  defp listeners_source(class, events, listeners, receiver) do
    table = {:map, Enum.map(events, &{event_atom(&1), String.downcase(&1["name"])})}

    funs =
      Enum.map_join(listeners, "\n\n", fn method ->
        name = snake(method)
        api_name = api_name(class["name"], method)

        doc =
          case method do
            m when m in ~w(off removeListener) -> "Removes an event listener added by `on/3` or `add_listener/3`."
            "once" -> "Adds an event listener that is removed after it is triggered once. See `on/3`."
            _ -> "Adds an event listener for `event`, see the module docs for the events."
          end

        """
        @doc #{inspect(doc)}
        @spec #{name}(t(), event(), (term() -> term())) :: t()
        def #{name}(#{receiver}, event, listener),
          do: #{inspect(impl(class["name"]))}.#{name}(#{receiver}, Facade.event!(event, @events, #{inspect(api_name)}), listener)
        """
      end)

    "@events #{render(table)}\n\n" <> funs
  end

  # --- types ---------------------------------------------------------------------

  # Schemas keep api.json order: `{:map, pairs}` is written as a map literal in that order.
  defp arg_schema(ctx, arg), do: schema(ctx, arg["type"])

  defp schema(_ctx, nil), do: nil

  defp schema(ctx, %{"union" => union}) when is_list(union) do
    {literals, others} = Enum.split_with(union, &literal?(&1["name"]))
    literals = for %{"name" => n} <- literals, n not in ["null", "undefined"], uniq: true, do: literal(n)
    schemas = Enum.flat_map(others, &List.wrap(schema(ctx, &1)))
    schemas = if literals == [], do: schemas, else: [{:enum, {:map, literals}} | schemas]

    case schemas do
      [] -> nil
      [one] -> one
      many -> {:union, many}
    end
  end

  defp schema(ctx, %{"properties" => props}) when is_list(props) and props != [] do
    pairs =
      for prop <- Enum.uniq_by(props, & &1["name"]),
          do: {atom(prop["name"]), {String.to_atom(prop["name"]), schema(ctx, prop["type"])}}

    {:object, {:map, pairs}}
  end

  defp schema(ctx, %{"name" => "Array", "templates" => [item]}) do
    if s = schema(ctx, item), do: {:array, s}
  end

  defp schema(_ctx, %{"name" => name}) do
    if literal?(name) and name not in ["null", "undefined"], do: {:enum, {:map, [literal(name)]}}
  end

  defp literal?(name), do: String.starts_with?(name, "\"") or name in ["null", "undefined"]

  defp literal(quoted) do
    value = String.trim(quoted, "\"")
    {value |> String.replace("-", "_") |> Macro.underscore() |> String.to_atom(), value}
  end

  @simple %{
    "string" => "String.t()",
    "path" => "String.t()",
    "URL" => "String.t()",
    "boolean" => "boolean()",
    "int" => "integer()",
    "long" => "integer()",
    "bigint" => "integer()",
    "float" => "number()",
    "number" => "number()",
    "Buffer" => "binary()",
    "RegExp" => "Regex.t()",
    "Date" => "DateTime.t()",
    "Error" => "Exception.t()",
    "function" => "fun()",
    "Function" => "fun()",
    "null" => ":null",
    "undefined" => "nil",
    "void" => "nil"
  }

  defp spec(ctx, type, dir, arg) do
    base = type_spec(ctx, type, dir)

    case arg do
      %{"name" => "options"} -> "keyword() | map()"
      %{"required" => false} -> "#{base} | nil"
      _ -> base
    end
  end

  defp type_spec(_ctx, nil, _dir), do: "nil"

  defp type_spec(ctx, %{"union" => union}, dir) when is_list(union),
    do: union |> Enum.map(&type_spec(ctx, &1, dir)) |> Enum.uniq() |> Enum.join(" | ")

  defp type_spec(_ctx, %{"properties" => props}, dir) when is_list(props) and props != [],
    do: if(dir == :in, do: "keyword() | map()", else: "map()")

  # `X | null` results are `nil` (`from_nullable`); `:null` is a JS value passed in.
  defp type_spec(_ctx, %{"name" => "null"}, :out), do: "nil"
  defp type_spec(ctx, %{"name" => "Array", "templates" => [item]}, dir), do: "[#{type_spec(ctx, item, dir)}]"
  defp type_spec(_ctx, %{"name" => "Object"}, _dir), do: "map()"

  defp type_spec(ctx, %{"name" => name}, _dir) do
    cond do
      Map.has_key?(@simple, name) -> @simple[name]
      String.starts_with?(name, "\"") -> inspect(elem(literal(name), 0))
      Map.has_key?(ctx.classes, name) -> "#{inspect(facade(name))}.t()"
      true -> "term()"
    end
  end

  # --- names and docs --------------------------------------------------------------

  # clientStackTrace.ts normalizeAPIName: "APIRequestContext" -> "apiRequestContext".
  defp api_name(class_name, member) do
    [_, head, rest] = Regex.run(~r/^(API|JS|CDP|[A-Z])(.*)$/, class_name)
    "#{String.downcase(head)}#{rest}.#{member}"
  end

  defp receiver(class_name, members) do
    receiver = snake(class_name)
    taken = for m <- members, a <- m["args"], do: var(a["name"])
    if receiver in taken, do: "this", else: receiver
  end

  defp event_atom(event), do: atom(event["name"])

  defp atom(js_name), do: js_name |> Macro.underscore() |> String.to_atom()

  defp snake(js_name), do: Macro.underscore(js_name)

  defp var(js_name) do
    name = snake(js_name)
    if name in @reserved, do: name <> "_", else: name
  end

  # " - text" for a list item, indented.
  defp bullet(text) when text in [nil, ""], do: ""
  defp bullet(text), do: " - " <> bullet_text(text)

  defp bullet_text(text),
    do: text |> String.trim() |> String.replace(~r/\n */, "\n    ") |> String.replace(~r/\n +\n/, "\n\n")

  defp first_line(text), do: text |> String.split("\n") |> hd()

  # JS code blocks only, `[method: Class.member]` links as facade functions where generated.
  defp comment(text, ctx) do
    text
    |> String.replace(~r/```(java|py|python|csharp|cs)\b.*?```\n*/s, "")
    |> String.replace(~r/\[`(method|property|event): (\w+)\.(\w+)`\]/, fn link ->
      [_, kind, class, member] = Regex.run(~r/\[`(\w+): (\w+)\.(\w+)`\]/, link)
      link(ctx, kind, class, member)
    end)
    |> String.replace(~r/\]\((\.\.\/|\.\/)?([\w\/-]+)\.md(#[\w-]*)?\)/, fn link ->
      [_, rel, page | anchor] = Regex.run(~r/\]\((\.\.\/|\.\/)?([\w\/-]+)\.md(#[\w-]*)?\)/, link)
      # Relative to docs/src/api/.
      "](https://playwright.dev/docs/#{if rel == "../", do: page, else: "api/" <> page}#{anchor})"
    end)
    |> String.replace(~r/\n{3,}/, "\n\n")
    |> String.trim()
  end

  defp link(ctx, kind, class, member) do
    with true <- kind in ["method", "property"],
         %{} = c <- ctx.classes[class],
         true <- member in ctx.exported[class],
         %{} = m <- Enum.find(c["members"], &(&1["alias"] == member)) do
      "`#{inspect(facade(class))}.#{snake(member)}/#{1 + length(m["args"])}`"
    else
      _ -> "`#{class}.#{member}`"
    end
  end

  defp doc(""), do: inspect("")

  defp doc(text) do
    if String.contains?(text, ~s(""")), do: inspect(text), else: ~s(~S"""\n#{text}\n""")
  end

  # Not `inspect/1`: it orders small atom-keyed maps by atom table position, which depends on
  # what the VM loaded before.
  defp render({:map, pairs}), do: "%{#{Enum.map_join(pairs, ", ", fn {k, v} -> "#{key(k)} #{render(v)}" end)}}"

  defp render(tuple) when is_tuple(tuple), do: "{#{tuple |> Tuple.to_list() |> Enum.map_join(", ", &render/1)}}"
  defp render(list) when is_list(list), do: "[#{Enum.map_join(list, ", ", &render/1)}]"
  defp render(term), do: inspect(term)

  defp key(atom), do: String.trim_leading(inspect(atom), ":") <> ":"

  defp format(source), do: IO.iodata_to_binary([Code.format_string!(source, line_length: 120), "\n"])

  defp write(path, source) do
    File.mkdir_p!(Path.dirname(path))
    File.write!(path, source)
    Mix.shell().info("Wrote #{path}")
  end
end

  # The option's type after its name, as NimbleOptions renders it; an object's fields follow as
  # nested bullets, so its maps read `map()`.
  defp option_bullet(ctx, prop, since),
    do: bullet(ctx, "`#{inspect(atom(prop["name"]))}` (#{linked_type(option_type(ctx, prop))})", prop, since)

  defp option_type(ctx, prop) do
    spec = prop_spec(ctx, prop)
    if props(prop["type"]) == [], do: spec, else: shallow_maps(spec)
  end

  # A type as ExDoc links it: each alternative of a union its own code span, types as `t:` refs
  # (`t:String.t/0`, `t:boolean/0`), lists as "list of", anything else (literals, functions,
  # dictionaries) as plain code.
  defp linked_type(spec), do: spec |> split_union() |> Enum.map_join(" | ", &linked_alternative/1)

  defp linked_alternative(type) do
    cond do
      type =~ ~r/^\[.*\]$/s ->
        "list of " <> linked_type(String.slice(type, 1..-2//1))

      match = Regex.run(~r/^((?:[A-Z]\w*\.)*)([a-z_]\w*)\(\)$/, type) ->
        "`t:#{Enum.at(match, 1)}#{Enum.at(match, 2)}/0`"

      true ->
        "`#{type}`"
    end
  end

  # The top-level alternatives of `a | [b | c] | %{d => e | f}`.
  defp split_union(spec), do: spec |> String.graphemes() |> split_union(0, "", [])
  defp split_union([], _depth, current, acc), do: Enum.reverse([String.trim(current) | acc])
  defp split_union(["|" | rest], 0, current, acc), do: split_union(rest, 0, "", [String.trim(current) | acc])

  defp split_union([c | rest], depth, current, acc) when c in ["[", "{", "("],
    do: split_union(rest, depth + 1, current <> c, acc)

  defp split_union([c | rest], depth, current, acc) when c in ["]", "}", ")"],
    do: split_union(rest, depth - 1, current <> c, acc)

  defp split_union([c | rest], depth, current, acc), do: split_union(rest, depth, current <> c, acc)

  # `%{...}` (balanced) as `map()`: the fields are listed below the option.
  defp shallow_maps(spec), do: spec |> String.graphemes() |> shallow_maps(0, "")
  defp shallow_maps([], _depth, acc), do: acc
  defp shallow_maps(["%", "{" | rest], 0, acc), do: shallow_maps(rest, 1, acc <> "map()")
  defp shallow_maps(["{" | rest], depth, acc) when depth > 0, do: shallow_maps(rest, depth + 1, acc)
  defp shallow_maps(["}" | rest], depth, acc) when depth > 0, do: shallow_maps(rest, depth - 1, acc)
  defp shallow_maps([_ | rest], depth, acc) when depth > 0, do: shallow_maps(rest, depth, acc)
  defp shallow_maps([c | rest], 0, acc), do: shallow_maps(rest, 0, acc <> c)

  defp field_bullet(ctx, prop, since), do: bullet(ctx, "`#{inspect(String.to_atom(prop["name"]))}`", prop, since)

  # "* name - doc", then the fields of an object type as nested bullets. Fields newer than
  # their parent say since when, as on playwright.dev.
  defp bullet(ctx, name, prop, since) do
    doc = md(prop["spec"], %{ctx | input: true})
    doc = if newer?(prop["since"], since), do: inline_join("*Since #{version(prop["since"])}.*", doc), else: doc

    item =
      cond do
        doc == "" -> "* #{name}"
        block_start?(doc) -> "* #{name}\n\n" <> indent(doc, 2)
        true -> "* #{name} - " <> indent(doc, 2, :hanging)
      end

    case props(prop["type"]) do
      [] ->
        item

      # Fields keep their JS names and values (`fontSize`, `'pointer'`).
      fields ->
        separator = if item =~ "\n\n", do: "\n\n", else: "\n"
        names = Map.merge(ctx.names, Map.new(fields, &{&1["name"], "`#{&1["name"]}`"}))
        ctx = %{ctx | names: names, literals: %{}}
        item <> separator <> indent(Enum.map_join(fields, "\n", &field_bullet(ctx, &1, prop["since"])), 2)
    end
  end

  defp block_start?(doc), do: doc =~ ~r/^(```|> |\* |- |\||\d+\. )/

  defp inline_join(head, ""), do: head
  defp inline_join(head, doc), do: if(block_start?(doc), do: head <> "\n\n" <> doc, else: head <> " " <> doc)

  # api.json versions are "v1.8"; ours mirror upstream's (see PLAN.md).
  defp version("v" <> version), do: version

  defp newer?(since, parent) when is_binary(since) and is_binary(parent),
    do: Version.compare(semver(since), semver(parent)) == :gt

  defp newer?(_since, _parent), do: false

  defp semver(since), do: since |> version() |> Kernel.<>(".0") |> Version.parse!()

  defp since(%{"since" => since}) when is_binary(since), do: "@doc since: #{inspect(version(since))}\n"
  defp since(_member), do: ""

  # Fields of an object type, also inside arrays and unions (`viewport: null|Object`).
  defp props(%{"properties" => props}) when is_list(props), do: Enum.uniq_by(props, & &1["name"])
  defp props(%{"name" => "Array", "templates" => [item]}), do: props(item)
  defp props(%{"union" => union}) when is_list(union), do: Enum.find_value(union, [], &(props(&1) != [] && props(&1)))
  defp props(_type), do: []

  defp deprecated(%{"deprecated" => text}) when is_binary(text),

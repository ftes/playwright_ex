  defp result_spec(ctx, %{"result" => %{"type" => type}}), do: " | " <> type_spec(ctx, type, :in)
  defp result_spec(_ctx, _arg), do: ""

  defp type_spec(_ctx, nil, _dir), do: "term()"

  # `string|Buffer`: JS branches on Buffer, a Buffer is `{:binary, bytes}` (PLAN, Decisions).
  defp type_spec(ctx, %{"union" => union}, dir) when is_list(union) do
    string_or_buffer? = Enum.any?(union, &(&1["name"] == "string")) and Enum.any?(union, &(&1["name"] == "Buffer"))

    union
    |> Enum.map(
      &if(string_or_buffer? and &1["name"] == "Buffer", do: "{:binary, binary()}", else: type_spec(ctx, &1, dir))
    )
    |> Enum.uniq()
    |> Enum.join(" | ")
  end

  defp type_spec(ctx, %{"name" => "Object", "templates" => [key, value]}, dir),
    do: "%{optional(#{type_spec(ctx, key, dir)}) => #{type_spec(ctx, value, dir)}}"

  # Objects are JS values both ways: results as the client returns them, inputs (nested in
  # options or positional) passed as they are, so a result can be passed back.
  defp type_spec(ctx, %{"properties" => props} = type, dir) when is_list(props) and props != [],
    do: object_spec(ctx, Enum.uniq_by(props, & &1["name"]), if(dir == :out, do: :out, else: :nested), type["open"])

  # `X | null` results are `nil` (`from_nullable`); `:null` is a JS value passed in.
  defp type_spec(_ctx, %{"name" => "null"}, :out), do: "nil"
  defp type_spec(_ctx, %{"name" => "\"" <> _}, dir) when dir in [:out, :nested], do: "String.t()"
  defp type_spec(ctx, %{"name" => "Array", "templates" => [item]}, dir), do: "[#{type_spec(ctx, item, dir)}]"

  defp type_spec(_ctx, %{"name" => "Object"}, _dir), do: "map()"
  defp type_spec(ctx, %{"name" => "Promise", "templates" => [value]}, dir), do: type_spec(ctx, value, dir)

  # `typeof TimeoutError` (`playwright.errors`): the exception module.
  defp type_spec(_ctx, %{"name" => "typeof", "templates" => [%{"name" => name}]}, _dir),
    do: inspect(Map.fetch!(@errors, name))

  # A callback: Playwright passes the arguments (outputs) and takes the result (an input).
  defp type_spec(ctx, %{"name" => "function", "args" => args} = fun, _dir) when is_list(args) do
    result =
      case fun["returnType"] do
        %{"name" => name} when name in ["void", "any", "Promise"] -> "term()"
        nil -> "term()"
        type -> type_spec(ctx, type, :in)
      end

    "(#{Enum.map_join(args, ", ", &type_spec(ctx, &1, :out))} -> #{result})"
  end

  defp type_spec(ctx, %{"name" => name}, _dir) do
    cond do
      Map.has_key?(@simple, name) -> @simple[name]
      String.starts_with?(name, "\"") -> inspect(elem(literal(name), 0))
      Map.has_key?(ctx.classes, name) -> "#{inspect(facade(name))}.t()"
      true -> "term()"
    end
  end

  # JS keys, `%{width: number(), height: number()}`.
  # An open object has more fields than documented: `optional(atom()) => term()`.
  defp object_spec(ctx, props, dir, open?) do
    fields = for p <- props, do: {p["required"], String.to_atom(p["name"]), type_spec(ctx, p["type"], dir)}

    cond do
      open? -> "%{#{Enum.map_join(fields, ", ", &map_field/1)}, optional(atom()) => term()}"
      Enum.all?(fields, &elem(&1, 0)) -> "%{#{Enum.map_join(fields, ", ", fn {_, k, t} -> "#{key(k)} #{t}" end)}}"
      true -> "%{#{Enum.map_join(fields, ", ", &map_field/1)}}"
    end
  end

  defp map_field({true, key, type}), do: "required(#{inspect(key)}) => #{type}"
  defp map_field({_, key, type}), do: "optional(#{inspect(key)}) => #{type}"

  # --- names and docs --------------------------------------------------------------

  # clientStackTrace.ts normalizeAPIName: "APIRequestContext" -> "apiRequestContext".
  defp api_name(class_name, member) do
    [_, head, rest] = Regex.run(~r/^(API|JS|CDP|[A-Z])(.*)$/, class_name)
    "#{String.downcase(head)}#{rest}.#{member}"
  end

  defp matcher_receiver(receivers), do: receivers |> Enum.map_join("_or_", &snake/1)

  defp receiver(class_name, members) do
    receiver = snake(class_name)
    taken = for m <- members, a <- m["args"], do: var(a["name"])
    if receiver in taken, do: "this", else: receiver
  end

  defp event_atom(event), do: atom(event["name"])

  defp atom(js_name), do: js_name |> Macro.underscore() |> String.to_atom()

  # Names that are no Elixir function names: Python's (`eval_on_selector`, `and_`).
  @renamed %{
    "$" => "query_selector",
    "$$" => "query_selector_all",
    "$eval" => "eval_on_selector",
    "$$eval" => "eval_on_selector_all",
    "and" => "and_",
    "or" => "or_",
    "not" => "not_"
  }

  defp snake(js_name), do: Map.get_lazy(@renamed, js_name, fn -> Macro.underscore(js_name) end)

  defp var(js_name) do
    name = snake(js_name)
    if name in @reserved, do: name <> "_", else: name
  end

  defp first_line(text), do: text |> String.split("\n") |> hd()

  # --- docs: rendered from the `spec` markdown AST (upstream utils/markdown.js) ---------

  # Code blocks for other clients (`python async`, `java`, ...) are dropped.
  @foreign_langs ~w(java csharp cs python py)

  defp md(nil, _ctx), do: ""

  defp md(nodes, ctx) do
    nodes
    |> Enum.flat_map(&block(&1, ctx))
    |> Enum.chunk_while(
      nil,
      fn
        {kind, text}, {kind, acc} when kind in [:li, :table, :quote, :link_def] -> {:cont, {kind, acc <> "\n" <> text}}
        block, nil -> {:cont, block}
        block, acc -> {:cont, elem(acc, 1), block}
      end,
      fn
        nil -> {:cont, nil}
        acc -> {:cont, elem(acc, 1), nil}
      end
    )
    |> Enum.join("\n\n")
  end

  defp block(%{"type" => "text", "text" => text}, ctx) do
    kind =
      cond do
        String.starts_with?(text, "|") -> :table
        String.starts_with?(text, ">") -> :quote
        text =~ ~r/^\[[^\]]+\]:/ -> :link_def
        true -> :text
      end

    [{kind, text(text, ctx)}]
  end

  # A JS example with a translation (`Mix.PlaywrightEx.Examples`) is shown in Elixir.
  defp block(%{"type" => "code", "codeLang" => lang, "lines" => lines} = node, ctx) do
    lang = lang |> String.split() |> hd()

    {lang, lines, comment} =
      case Map.fetch(ctx.examples, js_text(lines)) do
        {:ok, elixir} when lang == "js" -> {"elixir", String.split(elixir, "\n"), "#"}
        _ -> {lang, lines, "//"}
      end

    title = if node["title"], do: ["#{comment} #{node["title"]}"], else: []
    if lang in @foreign_langs, do: [], else: [{:code, Enum.join(["```#{lang}"] ++ title ++ lines ++ ["```"], "\n")}]
  end

  # `:::warning[Discouraged]` as an ExDoc admonition.
  defp block(%{"type" => "note", "noteType" => type} = node, ctx) do
    [_, kind | title] = Regex.run(~r/^(\w+)(?:\[(.*)\])?$/, type)
    class = Map.get(%{"note" => "info", "caution" => "warning", "danger" => "error"}, kind, kind)
    [{:note, note(Enum.at(title, 0, String.capitalize(kind)), class, md(node["children"], ctx))}]
  end

  defp block(%{"type" => "li", "liType" => type, "text" => text} = node, ctx) do
    marker = Map.fetch!(%{"bullet" => "*", "default" => "-", "ordinal" => "1."}, type)
    item = indent("#{marker} #{text(text, ctx)}", String.length(marker) + 1, :hanging)

    case md(node["children"], ctx) do
      "" -> [{:li, item}]
      children -> [{:li, item <> "\n" <> indent(children, String.length(marker) + 1)}]
    end
  end

  defp note(title, class, body), do: indent("#### #{title} {: .#{class}}\n\n#{body}", "> ")

  # Member refs (`[method: Page.goto]`), markdown links, inline code and raw type refs
  # (`[Promise]`), in one pass so that code and link texts are left alone.
  @inline ~r/\[`(method|property|event): (\w+)\.(\w+)(?:#\w+)?`\]|\[([^\]]*)\]\(([^)]*)\)|`([^`]+)`|\[([A-Za-z]\w*)\]/

  # Upstream joins the lines of a paragraph with `↵` (soft line breaks).
  defp text(text, ctx) do
    text
    |> String.replace("↵", "\n")
    |> null_inputs()
    |> then(
      &Regex.replace(@inline, &1, fn match, kind, class, member, label, href, code, type ->
        inline(ctx, match, {kind, class, member}, {label, href}, code, type)
      end)
    )
    |> prose()
    |> literal_values(ctx)
  end

  defp inline(ctx, _match, {kind, class, member}, _link, _code, _type) when kind != "",
    do: member_link(ctx, kind, class, member)

  defp inline(ctx, _match, _ref, {label, href}, _code, _type) when href != "", do: "[#{label}](#{href(ctx, href)})"

  defp inline(ctx, match, _ref, _link, code, "") when code != "",
    do: code_link(ctx, code) || prose_code(ctx, code) || match

  # `[Promise]`, `[string]`; not `[contenteditable]`.
  defp inline(ctx, match, _ref, _link, _code, type),
    do: code_link(ctx, type) || if(type =~ ~r/^[A-Z]|^string$/, do: "`#{type}`", else: match)

  # A facade function where generated, else playwright.dev (`linkUtils.js` createMarkdownLink).
  defp member_link(ctx, "event", class, event) do
    label = "`#{class}.on(#{inspect(atom(event))})`"

    if Map.has_key?(ctx.classes, class),
      do: "[#{label}](#{inspect(facade(class))}.html#module-#{atom(event)})",
      else: "[#{label}](#{dev_url(class)}##{kebab(class)}-event-#{kebab(event)})"
  end

  # By JS name or alias (`evalOnSelector` is `$eval`); assertion classes are `Expect`.
  defp member_link(ctx, kind, class, member) do
    facade_class = if class in ApiRules.assertion_classes(), do: "Expect", else: class

    with %{} = c <- ctx.classes[facade_class],
         %{} = m <- Enum.find(c["members"], &(member in [&1["alias"], &1["name"]] and &1["kind"] != "event")) do
      "`#{inspect(facade(facade_class))}.#{snake(m["alias"])}/#{1 + length(m["args"])}`"
    else
      _ when kind == "method" and member in @listener_methods and is_map_key(ctx.classes, class) ->
        "`#{inspect(facade(class))}.#{snake(member)}/3`"

      _ ->
        "[`#{class}.#{member}`](#{dev_url(class)}##{kebab(class)}-#{kebab(member)})"
    end
  end

  # --- docs: JS names in prose, as Elixir has them ---------------------------------

  defp receiver_name(class_name), do: api_name(class_name, "") |> String.trim_trailing(".")

  # The camelCase options of every member (`baseURL` in `Page.goto`'s docs is `Browser.newContext`'s).
  defp option_names(classes) do
    for class <- classes,
        member <- class["members"],
        %{"name" => "options", "type" => %{"properties" => props}} <- member["args"],
        %{"name" => name} <- props,
        name =~ ~r/[A-Z]/,
        into: %{},
        do: {name, "`#{inspect(atom(name))}`"}
  end

  # The member's own names first: arguments by JS name (`pageFunction` is `expression`), options,
  # the receiver (`elementHandle`); the enum literals of both (`'light'` is `:light`).
  defp member_names(ctx, args, keep) do
    {options, positional} = Enum.split_with(args, &(&1["name"] == "options"))
    props = for %{"type" => %{"properties" => props}} <- options, p <- props, do: p

    receiver = [{receiver_name(ctx.class), "`#{ctx.receiver}`"}]
    options = for p <- props, do: {p["name"], "`#{inspect(atom(p["name"]))}`"}
    arguments = for arg <- positional, name <- [arg["name"], arg["alias"]], name, do: {name, "`#{var(arg["name"])}`"}
    keep = for name <- keep, do: {name, "`#{name}`"}
    names = Map.new(receiver ++ options ++ arguments ++ keep)

    literals = for arg <- positional ++ props, {atom, value} <- literals(arg["type"]), into: %{}, do: {value, atom}
    %{ctx | names: names, literals: literals}
  end

  # The enum literals of every option, by option atom (`:service_workers` to `'block'`).
  defp option_literals(classes) do
    pairs =
      for class <- classes,
          member <- class["members"],
          %{"name" => "options", "type" => %{"properties" => props}} <- member["args"],
          prop <- props,
          {atom, value} <- literals(prop["type"]),
          do: {{atom(prop["name"]), value}, atom}

    Map.new(pairs)
  end

  # Unquoted enum values after "defaults to" (`:button` "Defaults to `left`"), and quoted ones
  # set for a named option ("setting `:service_workers` to `'block'`").
  defp literal_values(text, ctx) do
    text
    |> then(
      &Regex.replace(~r/\b([Dd]efaults\s+to\s+)`([\w-]+)`/, &1, fn whole, pre, value ->
        if atom = ctx.literals[value], do: pre <> "`#{inspect(atom)}`", else: whole
      end)
    )
    |> then(
      &Regex.replace(~r/`:(\w+)`(\s+to\s+)`'([\w-]+)'`/, &1, fn whole, option, to, value ->
        case ctx.option_literals[{String.to_atom(option), value}] do
          nil -> whole
          atom -> "`:#{option}`#{to}`#{inspect(atom)}`"
        end
      end)
    )
  end

  defp literals(%{"union" => union}) when is_list(union), do: Enum.flat_map(union, &literals/1)
  defp literals(%{"name" => "\"" <> _ = name}), do: [literal(name)]
  defp literals(_type), do: []

  # `null` passed in is `:null` (in argument and option docs, and "Passing `null`"); returned
  # (`X | null` results) and `undefined` it is `nil`.
  @null_input ~r/\b(Passing|passing|Pass|pass|Use|use|The|the)\s+`null`(?:\s+or\s+`undefined`)?|`null`(?=\s+(?:disables|resets|opts out))/

  defp null_inputs(text) do
    text
    |> then(
      &Regex.replace(@null_input, &1, fn match, word ->
        if word == "", do: "`:null`", else: String.replace(match, ~r/`.*/s, "`:null`")
      end)
    )
    |> String.replace("non-null", "non-nil")
  end

  # Wording of the JS calling convention.
  @prose [
    {~r/(Make\s+sure\s+to\s+)await\b/, "\\1call"},
    {~r/If the `callback` returns a `Promise`,(\s+)it will be awaited\./,
     "If `callback` returns a `PlaywrightEx.Promise`,\\1it is awaited."},
    {~r/async(\s+)listeners/, "running\\1listeners"},
    {~r/resolves\s+to\s+truthy\s+value/, "returns a truthy value"},
    {~r/\breturn\s+value\s+resolves\s+to\b/, "return value is"},
    {~r/\b(R|r)esolves\s+to\s+`nil`/, "\\1eturns `nil`"},
    {~r/\bIt\s+resolves\s+to\b/, "It returns"},
    {~r/\b(?:would|will)\s+resolve\s+(?:to|with)\b/, "returns"}
  ]

  defp prose(text), do: Enum.reduce(@prose, text, fn {re, to}, text -> Regex.replace(re, text, to) end)

  @js_call ~r/^([a-z]\w*)\.([a-z]\w*)(?:\(\w*\))?$/

  # Inline code in prose: `null`, JS names of arguments and options (`ignoreCase` is
  # `:ignore_case`), enum literals (`'light'`), `removeListener`, and JS calls on a facade class
  # (`page.goto()`, `browserContext.on(event)`) as links. Page-side JS (`setTimeout`,
  # `element.innerText`) and nested object keys (`certPath`, JS keys in Elixir too) stay.
  defp prose_code(ctx, "null"), do: if(ctx.input, do: "`:null`", else: "`nil`")
  defp prose_code(_ctx, "undefined"), do: "`nil`"

  defp prose_code(ctx, code) do
    cond do
      name = ctx.names[code] || ctx.options[code] -> name
      code in @listener_methods and code =~ ~r/[A-Z]/ and is_map_key(ctx.classes, ctx.class) -> "`#{snake(code)}/3`"
      true -> literal_code(ctx, code) || js_call(ctx, code)
    end
  end

  defp literal_code(ctx, code) do
    with [_, value] <- Regex.run(~r/^(['"])([^'"]*)\1$/, code, capture: :all_but_first),
         %{^value => atom} <- ctx.literals,
         do: "`#{inspect(atom)}`",
         else: (_ -> nil)
  end

  defp js_call(ctx, code) do
    with [receiver, member] <- Regex.run(@js_call, code, capture: :all_but_first),
         %{^receiver => class} <- ctx.receivers,
         "`" <> _ = link <- member_link(ctx, "method", class, member),
         do: link,
         else: (_ -> nil)
  end

  # A class name in code (`Browser`), or an error class (`TimeoutError`).
  defp code_link(ctx, name) do
    cond do
      Map.has_key?(@errors, name) -> "[`#{name}`](`#{inspect(@errors[name])}`)"
      Map.has_key?(ctx.classes, name) -> "[`#{name}`](`#{inspect(facade(name))}`)"
      name in ctx.all -> "[`#{name}`](#{dev_url(name)})"
      true -> nil
    end
  end

  # Links relative to docs/src/api/ (with or without `.md`) as playwright.dev URLs.
  defp href(ctx, href) do
    case Regex.run(~r/^(\.\.\/|\.\/)?([\w\/-]*?)(?:\.md)?(#[\w-]*)?$/, href) do
      [_, "", "" | anchor] ->
        "#{dev_url(ctx.class)}#{anchor}"

      [_, "../", page | anchor] ->
        "https://playwright.dev/docs/#{page}#{anchor}"

      [_, _, "class-" <> name = page | anchor] ->
        class_href(ctx, name, anchor) || "https://playwright.dev/docs/api/#{page}#{anchor}"

      [_, _, page | anchor] ->
        "https://playwright.dev/docs/api/#{page}#{anchor}"

      nil ->
        href
    end
  end

  defp class_href(ctx, lower, []) do
    case Enum.find(Map.keys(ctx.classes), &(String.downcase(&1) == lower)) do
      nil -> nil
      class -> "`#{inspect(facade(class))}`"
    end
  end

  defp class_href(_ctx, _lower, _anchor), do: nil

  defp dev_url(class), do: "https://playwright.dev/docs/api/class-#{String.downcase(class)}"

  # lodash kebabCase: "waitForURL" -> "wait-for-url".
  defp kebab(name), do: name |> Macro.underscore() |> String.replace("_", "-")

  defp sections(parts), do: parts |> Enum.filter(&(is_binary(&1) and &1 != "")) |> Enum.join("\n\n")

  defp indent(text, n, mode \\ :all)
  defp indent(text, n, mode) when is_integer(n), do: indent(text, String.duplicate(" ", n), mode)

  defp indent(text, prefix, mode) do
    [first | rest] = String.split(text, "\n")
    prefixed = Enum.map(rest, &if(&1 == "", do: String.trim_trailing(prefix), else: prefix <> &1))
    Enum.join([if(mode == :hanging, do: first, else: prefix <> first) | prefixed], "\n")
  end

  defp doc(""), do: inspect("")

  defp doc(text) do
    if String.contains?(text, ~s(""")), do: inspect(text), else: ~s(~S"""\n#{text}\n""")
  end

  # Not `inspect/1`: it orders small atom-keyed maps by atom table position, which depends on
  # what the VM loaded before.
  defp render({:map, pairs}), do: "%{#{Enum.map_join(pairs, ", ", fn {k, v} -> "#{key(k)} #{render(v)}" end)}}"

  defp render(tuple) when is_tuple(tuple), do: "{#{tuple |> Tuple.to_list() |> Enum.map_join(", ", &render/1)}}"
  defp render(list) when is_list(list), do: "[#{Enum.map_join(list, ", ", &render/1)}]"
  defp render(term), do: inspect(term)

  defp key(atom), do: String.trim_leading(inspect(atom), ":") <> ":"

  defp format(source), do: IO.iodata_to_binary([Code.format_string!(source, line_length: 120), "\n"])

  defp write(path, source) do
    File.mkdir_p!(Path.dirname(path))
    File.write!(path, source)
    Mix.shell().info("Wrote #{path}")
  end
end

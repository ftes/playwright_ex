  # _createChannel  -- ported as channel_call/5 (the Proxy `get` trap) and _channel/1 (its EventEmitter)
  #
  # Elixir only: `on_reply` (a 1-arity fun of the result) runs in the connection when the reply is
  # dispatched, before the next message. It is for the statements that follow `await` in JS when an
  # event the call enables reads what they write (`this._bindings.set(...)` before a
  # `bindingCall`): JS runs them before it dispatches that event, the caller's process may not.
  # It must not await; an exception it raises rejects the call. It does not run when the call fails.
  # Elixir only: `params` may be a 0-arity fun, called in the connection when the message is
  # written (one step with it): params computed from fields other processes write
  # (`_updateInterceptionPatterns`). It must not await.
  def channel_call(this, method, params, options \\ %{}, on_reply \\ nil) do
    method = to_string(method)
    type = get(this, :_type)
    # Elixir only: a disposed object's rows were deleted; JS still sends, and the server answers
    # for the unknown guid with a TargetClosedError (a collected one: see send_message_to_server).
    if !Heap.alive?(this) do
      _wrap_api_call(this, fn _ ->
        if _was_collected(this), do: raise("The object has been collected to prevent unbounded heap growth.")
        raise TargetClosedError.new()
      end)
    end

    # JS: a missing validator falls through to `obj[prop]`, i.e. `undefined is not a function`.
    validator =
      Validator.maybe_find_validator(type, method, "Params") || raise "#{type}.#{method} is not a protocol method"

    internal = (Metainfo.get_metainfo(%{type: type, method: method}) || %{})[:internal]

    _wrap_api_call(
      this,
      fn api_zone ->
        context = _validator_to_wire_context(this)

        validated_params =
          if is_function(params, 0),
            do: fn -> validator.(params.(), "", context) end,
            else: validator.(params, "", context)

        %{signal: signal, timeout: timeout} = Map.merge(%{signal: nil, timeout: 0}, options)

        if !api_zone.internal and _report(api_zone) do
          # Reporting/tracing/logging this api call for the first time.
          api_zone = Zones.update(:apiZone, &%{&1 | reported: true}) || api_zone

          # Elixir only: the listeners return what they assign (`data.callId = ...`).
          assigned =
            ClientInstrumentation.on_api_call_begin(get(this, :_instrumentation), api_zone, %{
              type: type,
              method: method,
              params: if(is_function(params, 0), do: params.(), else: params)
            })

          api_zone = _assign(api_zone, assigned)

          log_api_call(get(this, :_logger), "=> #{api_zone.apiName} started")

          Connection.send_message_to_server(
            get(this, :_connection),
            this,
            method,
            validated_params,
            Map.merge(api_zone, %{signal: signal, timeout: timeout, on_reply: on_reply})
          )
        else
          # Since this api call is either internal, or has already been reported/traced once,
          # passing as internal.
          Connection.send_message_to_server(get(this, :_connection), this, method, validated_params, %{
            internal: true,
            signal: signal,
            timeout: timeout,
            on_reply: on_reply
          })
        end
      end,
      %{internal: internal}
    )
  end

  def _wrap_api_call(this, func, options \\ %{}) do
    # Elixir only: a disposed object has no fields left (see `channel_call/4`).
    logger = if Heap.alive?(this), do: get(this, :_logger)
    instrumentation = if Heap.readable?(this), do: get(this, :_instrumentation)
    existing_api_zone = Zones.data(:apiZone)

    if existing_api_zone do
      func.(existing_api_zone)
    else
      stack_trace = ClientStackTrace.capture_library_stack_trace()
      api_name = stack_trace.apiName

      api_name =
        if String.starts_with?(api_name, "_") or String.contains?(api_name, "._"),
          do: options[:title] || api_name,
          else: api_name

      api_zone = %{
        title: options[:title],
        apiName: api_name,
        frames: stack_trace.frames,
        internal: options[:internal] || false,
        reported: false,
        # Elixir only: `reported` and the listeners' fields, shared by the processes the call
        # starts (see `_report/1`, `_assign/2`).
        _reportedCell: :atomics.new(2, []),
        _pid: self(),
        userData: nil,
        callId: nil
      }

      try do
        result = Zones.with(:apiZone, api_zone, fn -> func.(api_zone) end)

        if !options[:internal] do
          log_api_call(logger, "<= #{api_zone.apiName} succeeded")
          ClientInstrumentation.on_api_call_end(instrumentation, _assigned(api_zone))
        end

        result
      rescue
        e ->
          # const innerError = ...  -- not ported: stack rewriting (Elixir keeps __STACKTRACE__)
          e =
            if api_zone.apiName != "" and !String.contains?(api_zone.apiName, "<anonymous>") and
                 Map.has_key?(e, :message),
               do: Map.put(e, :message, api_zone.apiName <> ": " <> Exception.message(e)),
               else: e

          # const stackFrames = ...; e.stack = ...  -- not ported: stack rewriting

          if !options[:internal] do
            api_zone = Map.put(_assigned(api_zone), :error, e)
            log_api_call(logger, "<= #{api_zone.apiName} failed")
            ClientInstrumentation.on_api_call_end(instrumentation, api_zone)
          end

          reraise e, __STACKTRACE__
      catch
        # Elixir only: an exit or throw, as JS's `catch` gets any thrown value: `error` is
        # `{kind, reason}`.
        kind, reason ->
          if !options[:internal] do
            api_zone = Map.put(_assigned(api_zone), :error, {kind, reason})
            log_api_call(logger, "<= #{api_zone.apiName} failed")
            ClientInstrumentation.on_api_call_end(instrumentation, api_zone)
          end

          :erlang.raise(kind, reason, __STACKTRACE__)
      end
    end
  end

  @doc false
  # Elixir only: `!apiZone.reported` then `apiZone.reported = true`, for the zone's one object in
  # JS. The zone is copied into each process the call starts (`Promise.async`), so the flag is a
  # shared cell, set once: true for the first caller only.
  def _report(%{_reportedCell: cell}), do: :atomics.compare_exchange(cell, 1, 0, 1) == :ok
  def _report(api_zone), do: !api_zone.reported

  @doc false
  # Elixir only: what the `onApiCallBegin` listeners assign (`data.callId = ...`, `data.userData =
  # ...`; `ClientInstrumentation.on_api_call_begin/3` returns it), set on the zone's one object in
  # JS, where the call's message and `onApiCallEnd` read it. Here it goes into the calling
  # process's copy of the zone, and for `_wrapApiCall`'s `onApiCallEnd` (`_assigned/1`) into the
  # zone's process dictionary, or into the `Playwright.Runtime.ProcessOwner.zones/0` table
  # when another process reported the call (`_report/1`), keyed `{zone's pid, cell}`. The
  # `_reportedCell`'s second slot is 1 once it is in the table, 2 once the call ended: a call
  # reported after it ended (not awaited) drops it, as JS's `onApiCallEnd` came first. The table
  # drops the rows of a zone's process that exits before its call ends (killed): its call never
  # ends, as a JS call that never settles, whose step stays open.
  def _assign(api_zone, nil), do: api_zone

  def _assign(api_zone, assigned) do
    api_zone = Zones.update(:apiZone, &Map.merge(&1, assigned)) || Map.merge(api_zone, assigned)

    case api_zone do
      %{_reportedCell: cell, _pid: pid} when pid == self() ->
        Process.put({__MODULE__, cell}, assigned)

      %{_reportedCell: cell, _pid: pid} ->
        :ets.insert(ProcessOwner.zones(), {{pid, cell}, assigned})
        ProcessOwner.monitor_zones(pid)
        if :atomics.compare_exchange(cell, 2, 0, 1) != :ok, do: :ets.delete(ProcessOwner.zones(), {pid, cell})

      _api_zone ->
        nil
    end

    api_zone
  end

  # The zone `onApiCallEnd` gets: with what the listeners assigned (see `_assign/2`).
  defp _assigned(%{_reportedCell: cell} = api_zone) do
    in_table? = :atomics.exchange(cell, 2, 2) == 1

    case Process.delete({__MODULE__, cell}) do
      nil when in_table? ->
        case :ets.take(ProcessOwner.zones(), {self(), cell}) do
          [{_cell, assigned}] -> Map.merge(api_zone, assigned)
          [] -> api_zone
        end

      nil ->
        api_zone

      assigned ->
        Map.merge(api_zone, assigned)
    end
  end


  # `struct:` names the facade module of a public class (`struct: Playwright.Page`): the handle
  # is the facade's struct, generated by `mix playwright.gen.api` from `__struct_fields__/0`.
  defmacro __using__(opts) do
    struct = Macro.expand(Keyword.get(opts, :struct), __CALLER__) || __CALLER__.module

    struct_def =
      if struct == __CALLER__.module,
        do: quote(do: defstruct([:guid, :conn, :table, :type, :initializer])),
        else: quote(do: def(__struct_fields__, do: [:guid, :conn, :table, :type, :initializer]))

    quote do
      use Playwright.Client.EventEmitter
      use Playwright.Client.Decorators

      import Playwright.Client.ChannelOwner,
        only: [channel_call: 3, channel_call: 4, channel_call: 5, _channel: 1]


      def __channel_owner__, do: true
    end
  end

  @doc false
  def inspect_handle(%module{guid: guid}) do
    # A runtime object sharing a handle struct (`DisposableStub`) has a ref or tuple as its guid.
    guid = if is_binary(guid), do: guid, else: inspect(guid)
    "#" <> (module |> Module.split() |> List.delete("Client") |> Enum.join(".")) <> "<#{guid}>"
  end

  # `x instanceof ChannelOwner`
  def is_channel_owner(this) when is_struct(this), do: function_exported?(impl(this), :__channel_owner__, 0)
  def is_channel_owner(_), do: false

  def new(module, parent, type, guid, initializer) do
    connection = if is_channel_owner(parent), do: get(parent, :_connection), else: parent

    this =
      struct(module.__handle__(),
        guid: guid,
        conn: connection.conn,
        table: connection.table,
        type: type,
        initializer: initializer
      )

    # super();  -- EventEmitter state is heap fields
    # this._connection = ...; this._type = type; this._guid = guid;  -- in the handle
    # Elixir only: a disposed object of this guid gives way (`_forget_disposed/1`).
    _forget_disposed(this)
    # Elixir only: registered first, its fields are rows of a live object.
    map_set(connection, :_objects, guid, this)
    # this.setMaxListeners(0);  (once registered)
    EventEmitter.set_max_listeners(this, 0)
    put(this, :_parent, if(is_channel_owner(parent), do: parent))
    put(this, :_instrumentation, get(connection, :_instrumentation))

    if get(this, :_parent) do
      map_set(get(this, :_parent), :_objects, guid, this)
      put(this, :_logger, get(get(this, :_parent), :_logger))
    end

    # this._channel = this._createChannel(new EventEmitter());  -- see channel_call/4 and _channel/1
    # this._initializer = initializer;  -- in the handle
    this
  end

  # The EventEmitter behind `this._channel` (protocol events): owned by the object.
  def _channel(this), do: %EventEmitter{guid: {this.guid, :channel}, conn: this.conn, table: this.table}

  def _set_event_to_subscription_mapping(this, mapping) do
    put(this, :_eventToSubscriptionMapping, mapping)
  end

  @doc false
  # In the connection: posted without awaiting (upstream: `.catch(() => {})`), so it is ordered
  # before any later call.
  def _update_subscription(this, event, enabled) do
    protocol_event = (get(this, :_eventToSubscriptionMapping) || %{})[event]

    if protocol_event do
      _post(this, :updateSubscription, %{event: protocol_event, enabled: enabled})
    end
  end

  @doc false
  # Elixir only, in the connection: an internal call whose result is dropped (a message, no await).
  def _post(this, method, params) do
    method = to_string(method)
    validator = Validator.find_validator(this.type, method, "Params")
    validated = validator.(params, "", _validator_to_wire_context(this))
    Connection.post(get(this, :_connection), this, method, validated)
  end

  def on(this, event, listener), do: _add(this, event, listener, false, false)
  def add_listener(this, event, listener), do: _add(this, event, listener, false, false)
  def prepend_listener(this, event, listener), do: _add(this, event, listener, true, false)
  # Upstream: EventEmitter's `once` calls `this.on`, overridden here.
  def once(this, event, listener), do: _add(this, event, listener, false, true)

  # `if (!this.listenerCount(event)) this._updateSubscription(event, true); super.on(event, listener);`
  # Elixir only: atomic, in the connection.
  defp _add(this, event, listener, prepend, once) do
    entry = EventEmitter.entry(this, listener, once)
    _add_entry(this, event, entry, prepend)
    this
  end

  defp _add_entry(this, event, entry, prepend) do
    Heap.atomic(this, fn ->
      if listener_count(this, event) == 0 and Heap.alive?(this), do: _update_subscription(this, event, true)
      EventEmitter._insert(this, event, entry, prepend)
    end)
  end

  # EventEmitter.subscribe/3 (a waiter's listener), through addListener.
  def subscribe(this, event, predicate \\ nil) do
    {entry, promise} = EventEmitter._subscription(this, event, predicate)
    _add_entry(this, event, entry, false)
    promise
  end

  def off(this, event, listener), do: remove_listener(this, event, listener)

  # Elixir only: a no-op on a closed connection process (`EventEmitter._unless_closed/1`).
  def remove_listener(this, event, listener) do
    EventEmitter._unless_closed(fn ->
      Heap.atomic(this, fn ->
        EventEmitter._take(this, event, listener)
        if listener_count(this, event) == 0 and Heap.alive?(this), do: _update_subscription(this, event, false)
      end)
    end)

    this
  end

  defp listener_count(this, event), do: EventEmitter.listener_count(this, event)

  def _adopt(this, child) do
    map_delete(get(child, :_parent), :_objects, child.guid)
    map_set(this, :_objects, child.guid, child)
    put(child, :_parent, this)
  end

  def _parent_of_type(this, type) do
    parent = get(this, :_parent)

    cond do
      parent == nil -> nil
      get(parent, :_type) == type -> parent
      true -> _parent_of_type(parent, type)
    end
  end

  def _dispose(this, reason) do
    # Clean up from parent and connection.
    if get(this, :_parent), do: map_delete(get(this, :_parent), :_objects, this.guid)
    # this._wasCollected = reason === 'gc';  -- see _retire/2 and _was_collected/1
    objects = map_values(this, :_objects)
    map_delete(get(this, :_connection), :_objects, this.guid)

    # Dispose all children.
    for object <- objects, do: _dispose(object, reason)
    # this._objects.clear();  -- not ported: a disposed object's rows are kept (below), its children are gone
    _retire(this, reason)
  end

  # Elixir only, in the connection. JS keeps a disposed object readable (its last field values,
  # its settled promises) while referenced. Here its rows are retained, then freed:
  #   * under a BrowserContext still open (a closed page, a detached frame, a resolved
  #     BindingCall, the context's `request` disposed by its close): kept with the context, whose
  #     own code may still read them (`_on_close` reads `request.tracing`), until it is disposed;
  #   * else, and then, in the connection's FIFO of disposed objects (`Conn.retain/2`), children
  #     (and the objects kept with a context) before their parent. Once it retains more than its
  #     cap of rows, the oldest are freed, a page before its context (`Conn.trim/2`, after each
  #     `__dispose__`, which spares the objects it disposed).
  # Its listeners go (they never fire again; user listener processes stop) and pending latches
  # are rejected. An object the driver collected (`reason: "gc"`) is freed at once (deviation: JS
  # still reads its fields); its tombstone (`_wasCollected`) is kept apart, bounded by a count of
  # its own (`Conn.collected/2`). A handle disposed by itself and a JsonPipe are freed at once,
  # without one (`_free_at_dispose?/2`).
  # deviation: reads of a freed object raise TargetClosedError (JS: GC while referenced), but
  # those of the closed-state getters (`Heap.get_or_freed/3`).
  defp _retire(this, reason) do
    error = TargetClosedError.new()
    rows = Heap.rows(this, this.guid)

    for {local, value} <- rows do
      case {sub(local), value} do
        {{:map, :_events, _}, {_seq, entries}} ->
          for %{kind: :user, pid: pid} <- entries, do: send(pid, :pw_stop)
          :ets.delete(this.table, {this.guid, local})

        {{:latch, _}, {:pending, waiters}} ->
          for {pid, ref} <- waiters, do: Conn.wake(pid, {:pw, ref, {:error, error}})
          :ets.insert(this.table, {{this.guid, local}, {:settled, {:error, error}}})

        _ ->
          :ok
      end
    end

    free? = _free_at_dispose?(this, reason) or reason == "gc"
    context = if !free?, do: _open_context(get(this, :_parent))

    # The objects kept with this context: to the FIFO, oldest first.
    if !context do
      for {{:kept, n}, guid} <- rows do
        :ets.delete(this.table, {this.guid, {:kept, n}})
        Conn.retain(this.table, guid)
      end
    end

    cond do
      free? ->
        Heap.free_rows(this, this.guid)
        if reason == "gc", do: Conn.collected(this.table, this.guid)

      context ->
        n = :erlang.unique_integer([:monotonic])

        :ets.insert(this.table, [
          {{this.guid, :__retained__}, {:kept, context.guid, n}},
          {{context.guid, {:kept, n}}, this.guid}
        ])

      true ->
        Conn.retain(this.table, this.guid)
    end
  end

  # The nearest BrowserContext ancestor, if open.
  defp _open_context(nil), do: nil

  defp _open_context(object) do
    if get(object, :_type) == "BrowserContext",
      do: if(Heap.alive?(object), do: object),
      else: _open_context(get(object, :_parent))
  rescue
    # An ancestor freed already.
    TargetClosedError -> nil
  end

  # Objects freed at once instead of retained:
  #   * a JSHandle or ElementHandle the driver disposed by itself (`JSHandle.dispose`; a parent's
  #     dispose removes the parent from the connection first). JS frees it once unreferenced;
  #     kept with its open context, a long-lived page would grow with the handles it disposed.
  #     Calls raise TargetClosedError, as in JS (the driver no longer knows the guid). deviation:
  #     so do field reads, and `to_string/1` (JS: the last preview).
  #   * a JsonPipe (a remote connection's, on the local LocalUtils): only its transport uses it,
  #     whose calls after close raise and are dropped, as in JS.
  defp _free_at_dispose?(this, reason) do
    case get(this, :_type) do
      type when type in ["JSHandle", "ElementHandle"] -> reason != "gc" and Heap.alive?(get(this, :_parent))
      "JsonPipe" -> true
      _ -> false
    end
  end

  # Elixir only, in the connection (`__create__`): the driver creates an object under the guid of
  # one it disposed, a new dispatcher for the same server object (`newContextForReuse` after
  # `disconnectFromReusedContext`: the context and its pages; a `gc`-collected object referenced
  # again). deviation: JS has two objects, the disposed one readable while referenced; here rows
  # are keyed by guid, so the disposed one's retention ends now (its rows, its tombstone, its FIFO
  # entry or its context's row). Kept, its eviction later would free the new object's rows, and
  # its stale fields would be the new one's.
  defp _forget_disposed(%{table: table, guid: guid}) when is_binary(guid) do
    case {:ets.lookup(table, {guid, :__retained__}), :ets.lookup(table, {guid, :__collected__})} do
      {[], []} ->
        :ok

      {retained, collected} ->
        case retained do
          [{_, {:kept, context, n}}] -> :ets.delete(table, {context, {:kept, n}})
          [{_, seq}] -> Conn.forget(table, seq)
          [] -> :ok
        end

        with [{_, seq}] <- collected, do: Conn.forget_collected(table, seq)
        Heap.free_rows(%{table: table}, guid)
    end
  end

  defp _forget_disposed(_this), do: :ok

  @doc false
  # `this._wasCollected`: the driver collected it (`__dispose__` with reason "gc").
  def _was_collected(%{table: table, guid: guid}) when is_binary(guid) do
    :ets.member(table, {guid, :__collected__})
  rescue
    ArgumentError -> false
  end

  def _was_collected(_this), do: false


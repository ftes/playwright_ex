defmodule PlaywrightEx.Client.ChannelOwner do
  @upstream "packages/playwright-core/src/client/channelOwner.ts"
  @moduledoc """
  Port of `#{@upstream}`.

  `abstract class ChannelOwner extends EventEmitter` becomes `use PlaywrightEx.Client.ChannelOwner`,
  which injects the struct (`guid`, `conn`, `table`, `type`, `initializer`; the facade's for a
  public class, see `__using__/1`) and the inherited methods; `super(...)` in a
  subclass constructor is `ChannelOwner.new(__MODULE__, parent, type, guid, initializer)`.

  Deviations: the `this._channel` Proxy is `channel_call(this, :method, params, options)`,
  and its event side is the separate emitter `_channel(this)`. Channels and their owners are
  the same handle, so `X.from(channel)` is the identity.

  The handle carries the immutable part of the object (its connection process and table, `type`,
  `initializer`); its fields are rows of the connection (`PlaywrightEx.Runtime.Heap`), deleted by
  `_dispose`.
  """
  import PlaywrightEx.Runtime.Heap

  alias PlaywrightEx.Client.ClientHelper
  alias PlaywrightEx.Client.ClientInstrumentation
  alias PlaywrightEx.Client.ClientStackTrace
  alias PlaywrightEx.Client.Connection
  alias PlaywrightEx.Client.EventEmitter
  alias PlaywrightEx.Protocol.Metainfo
  alias PlaywrightEx.Runtime.Conn
  alias PlaywrightEx.Protocol.Validator
  alias PlaywrightEx.Protocol.ValidatorPrimitives.ValidationError
  alias PlaywrightEx.Runtime.Heap
  alias PlaywrightEx.Runtime.Zones
  alias PlaywrightEx.TargetClosedError

  require Logger

  # `struct:` names the facade module of a public class (`struct: PlaywrightEx.Page`): the handle
  # is the facade's struct, generated by `mix playwright_ex.gen.api` from `__struct_fields__/0`.
  defmacro __using__(opts) do
    struct = Macro.expand(Keyword.get(opts, :struct), __CALLER__) || __CALLER__.module

    struct_def =
      if struct == __CALLER__.module,
        do: quote(do: defstruct([:guid, :conn, :table, :type, :initializer])),
        else: quote(do: def(__struct_fields__, do: [:guid, :conn, :table, :type, :initializer]))

    quote do
      use PlaywrightEx.Client.EventEmitter

      import PlaywrightEx.Client.ChannelOwner, only: [channel_call: 3, channel_call: 4, channel_call: 5, _channel: 1]
      import PlaywrightEx.Runtime.Heap

      alias PlaywrightEx.Client.ChannelOwner
      alias PlaywrightEx.Client.EventEmitter
      alias PlaywrightEx.Client.Events
      alias PlaywrightEx.Client.TimeoutSettings
      alias PlaywrightEx.Runtime.Promise

      @doc false
      unquote(struct_def)

      @doc false
      def __handle__, do: unquote(struct)

      # Elixir only: `#PlaywrightEx.Browser<browser@...>`, named after the public module.
      defimpl Inspect, for: unquote(struct) do
        def inspect(this, _opts), do: PlaywrightEx.Client.ChannelOwner.inspect_handle(this)
      end

      defdelegate on(this, event, listener), to: ChannelOwner
      defdelegate once(this, event, listener), to: ChannelOwner
      defdelegate add_listener(this, event, listener), to: ChannelOwner
      defdelegate prepend_listener(this, event, listener), to: ChannelOwner
      defdelegate off(this, event, listener), to: ChannelOwner
      defdelegate remove_listener(this, event, listener), to: ChannelOwner
      defdelegate subscribe(this, event, predicate \\ nil), to: ChannelOwner
      defdelegate _wrap_api_call(this, func, options \\ %{}), to: ChannelOwner
      defdelegate _parent_of_type(this, type), to: ChannelOwner
      defdelegate _set_event_to_subscription_mapping(this, mapping), to: ChannelOwner
      def __channel_owner__, do: true
    end
  end

  @doc false
  def inspect_handle(%module{guid: guid}) do
    "#" <> (module |> Module.split() |> List.delete("Client") |> Enum.join(".")) <> "<#{guid}>"
  end

  # `x instanceof ChannelOwner`
  def is_channel_owner(this) when is_struct(this), do: function_exported?(impl(this), :__channel_owner__, 0)
  def is_channel_owner(_), do: false

  def new(module, parent, type, guid, initializer) do
    connection = if is_channel_owner(parent), do: get(parent, :_connection), else: parent

    this =
      struct(module.__handle__(),
        guid: guid,
        conn: connection.conn,
        table: connection.table,
        type: type,
        initializer: initializer
      )

    # super();  -- EventEmitter state is heap fields
    # this.setMaxListeners(0);  -- not ported: no listener leak warning in EventEmitter
    # this._connection = ...; this._type = type; this._guid = guid;  -- in the handle
    # Elixir only: registered first, its fields are rows of a live object.
    map_set(connection, :_objects, guid, this)
    put(this, :_parent, if(is_channel_owner(parent), do: parent))
    put(this, :_instrumentation, get(connection, :_instrumentation))

    if get(this, :_parent) do
      map_set(get(this, :_parent), :_objects, guid, this)
      put(this, :_logger, get(get(this, :_parent), :_logger))
    end

    # this._channel = this._createChannel(new EventEmitter());  -- see channel_call/4 and _channel/1
    # this._initializer = initializer;  -- in the handle
    this
  end

  # The EventEmitter behind `this._channel` (protocol events): owned by the object.
  def _channel(this), do: %EventEmitter{guid: {this.guid, :channel}, conn: this.conn, table: this.table}

  def _set_event_to_subscription_mapping(this, mapping) do
    put(this, :_eventToSubscriptionMapping, mapping)
  end

  # In the connection: posted without awaiting (upstream: `.catch(() => {})`), so it is ordered
  # before any later call.
  defp _update_subscription(this, event, enabled) do
    protocol_event = (get(this, :_eventToSubscriptionMapping) || %{})[event]

    if protocol_event do
      _post(this, :updateSubscription, %{event: protocol_event, enabled: enabled})
    end
  end

  @doc false
  # Elixir only, in the connection: an internal call whose result is dropped (a message, no await).
  def _post(this, method, params) do
    method = to_string(method)
    validator = Validator.find_validator(this.type, method, "Params")
    validated = validator.(params, "", _validator_to_wire_context(this))
    Connection.post(get(this, :_connection), this, method, validated)
  end

  def on(this, event, listener), do: _add(this, event, listener, false, false)
  def add_listener(this, event, listener), do: _add(this, event, listener, false, false)
  def prepend_listener(this, event, listener), do: _add(this, event, listener, true, false)
  # Upstream: EventEmitter's `once` calls `this.on`, overridden here.
  def once(this, event, listener), do: _add(this, event, listener, false, true)

  # `if (!this.listenerCount(event)) this._updateSubscription(event, true); super.on(event, listener);`
  # Elixir only: atomic, in the connection.
  defp _add(this, event, listener, prepend, once) do
    entry = EventEmitter.entry(this, listener, once)
    _add_entry(this, event, entry, prepend)
    this
  end

  defp _add_entry(this, event, entry, prepend) do
    Heap.atomic(this, fn ->
      if listener_count(this, event) == 0 and Heap.alive?(this), do: _update_subscription(this, event, true)
      EventEmitter._insert(this, event, entry, prepend)
    end)
  end

  # EventEmitter.subscribe/3 (a waiter's listener), through addListener.
  def subscribe(this, event, predicate \\ nil) do
    {entry, promise} = EventEmitter._subscription(this, event, predicate)
    _add_entry(this, event, entry, false)
    promise
  end

  def off(this, event, listener), do: remove_listener(this, event, listener)

  def remove_listener(this, event, listener) do
    Heap.atomic(this, fn ->
      EventEmitter._take(this, event, listener)
      if listener_count(this, event) == 0 and Heap.alive?(this), do: _update_subscription(this, event, false)
    end)

    this
  end

  defp listener_count(this, event), do: EventEmitter.listener_count(this, event)

  def _adopt(this, child) do
    map_delete(get(child, :_parent), :_objects, child.guid)
    map_set(this, :_objects, child.guid, child)
    put(child, :_parent, this)
  end

  def _parent_of_type(this, type) do
    parent = get(this, :_parent)

    cond do
      parent == nil -> nil
      get(parent, :_type) == type -> parent
      true -> _parent_of_type(parent, type)
    end
  end

  def _dispose(this, reason) do
    # Clean up from parent and connection.
    if get(this, :_parent), do: map_delete(get(this, :_parent), :_objects, this.guid)
    # this._wasCollected = reason === 'gc';  -- not ported: a collected object's rows are freed at once (below)
    objects = map_values(this, :_objects)
    map_delete(get(this, :_connection), :_objects, this.guid)

    # Dispose all children.
    for object <- objects, do: _dispose(object, reason)
    # this._objects.clear();  -- not ported: a disposed object's rows are kept (below), its children are gone
    _retire(this, reason)
  end

  # Elixir only, in the connection. JS keeps a disposed object readable (its last field values,
  # its settled promises) while referenced. Here its rows are kept until its anchor is freed:
  #   * a BrowserContext or Browser: the processes that created or closed it (`_set_creator/1`,
  #     inherited from the parent chain; else the connection), freed when the last one exits;
  #   * anything else: the nearest BrowserContext (else Browser) ancestor, freed with it.
  # Its listeners go (they never fire again; user listener processes stop) and pending latches
  # are rejected. An object the driver collected (`reason: "gc"`) is freed at once (JS: unusable).
  # deviation: reads after those processes exit raise TargetClosedError (JS: GC while
  # referenced); a long-lived process keeps the contexts it closed (~175 rows each) until it exits.
  defp _retire(this, reason) do
    error = TargetClosedError.new()

    for {local, value} <- Heap.rows(this, this.guid) do
      case {sub(local), value} do
        {{:map, :_events, _}, {_seq, entries}} ->
          for %{kind: :user, pid: pid} <- entries, do: send(pid, :pw_stop)
          :ets.delete(this.table, {this.guid, local})

        {{:latch, _}, {:pending, waiters}} ->
          for {pid, ref} <- waiters, do: send(pid, {:pw, ref, {:error, error}})
          :ets.insert(this.table, {{this.guid, local}, {:settled, {:error, error}}})

        _ ->
          :ok
      end
    end

    if reason == "gc" do
      Heap.release(this.table, this.guid)
    else
      :ets.insert(this.table, {{this.guid, :__retained__}, true})

      case _anchor(this) do
        {:processes, pids} -> for pid <- pids, do: Conn.anchor(this.table, pid, this.guid)
        anchor -> :ets.insert(this.table, {{anchor, {:retained, this.guid}}, true})
      end
    end
  end

  defp _anchor(this) do
    if get(this, :_type) in ["BrowserContext", "Browser"],
      do: _creator(this),
      else: _anchor(get(this, :_parent), ["BrowserContext", "Browser"])
  end

  defp _anchor(nil, _types), do: :connection

  defp _anchor(object, types) do
    if get(object, :_type) in types, do: object.guid, else: _anchor(get(object, :_parent), types)
  rescue
    # An ancestor freed already (not expected: children are disposed first).
    TargetClosedError -> :connection
  end

  defp _creator(nil), do: :connection

  defp _creator(object) do
    case get(object, :_creators) do
      [_ | _] = pids -> {:processes, pids}
      _ -> _creator(get(object, :_browser) || get(object, :_parent))
    end
  rescue
    TargetClosedError -> :connection
  end

  @doc false
  # Elixir only: records the calling process as the creator of a BrowserContext or Browser it
  # obtained or closes (the retention anchor of its rows after dispose, see `_retire/2`).
  def _set_creator(this) do
    if !Conn.in_conn?(), do: set_add(this, :_creators, self())
    this
  end

  defp sub({:latch, _} = sub), do: sub
  defp sub({:map, _, _} = sub), do: sub
  defp sub({_owned, sub}), do: sub
  defp sub(sub), do: sub

  # _debugScopeState  -- not ported

  defp _validator_to_wire_context(this) do
    under_test = Connection._is_under_test(get(this, :_connection))

    %{
      tChannelImpl: &t_channel_impl_to_wire/4,
      binary: if(Connection.raw_buffers(get(this, :_connection)), do: "buffer", else: "toBase64"),
      isUnderTest: fn -> under_test end
    }
  end

  # _createChannel  -- ported as channel_call/5 (the Proxy `get` trap) and _channel/1 (its EventEmitter)
  #
  # Elixir only: `on_reply` (a 1-arity fun of the result) runs in the connection when the reply is
  # dispatched, before the next message. It is for the statements that follow `await` in JS when an
  # event the call enables reads what they write (`this._bindings.set(...)` before a
  # `bindingCall`): JS runs them before it dispatches that event, the caller's process may not.
  # It must not await; an exception it raises rejects the call. It does not run when the call fails.
  def channel_call(this, method, params, options \\ %{}, on_reply \\ nil) do
    method = to_string(method)
    type = get(this, :_type)
    # Elixir only: a disposed object's rows were deleted; JS still sends, and the server answers
    # for the unknown guid with a TargetClosedError.
    if !Heap.alive?(this), do: _wrap_api_call(this, fn _ -> raise TargetClosedError.new() end)

    # JS: a missing validator falls through to `obj[prop]`, i.e. `undefined is not a function`.
    validator =
      Validator.maybe_find_validator(type, method, "Params") || raise "#{type}.#{method} is not a protocol method"

    internal = (Metainfo.get_metainfo(%{type: type, method: method}) || %{})[:internal]

    _wrap_api_call(
      this,
      fn api_zone ->
        validated_params = validator.(params, "", _validator_to_wire_context(this))
        %{signal: signal, timeout: timeout} = Map.merge(%{signal: nil, timeout: 0}, options)

        if !api_zone.internal and !api_zone.reported do
          # Reporting/tracing/logging this api call for the first time.
          api_zone = Zones.update(:apiZone, &%{&1 | reported: true}) || api_zone

          ClientInstrumentation.on_api_call_begin(get(this, :_instrumentation), api_zone, %{
            type: type,
            method: method,
            params: params
          })

          log_api_call(get(this, :_logger), "=> #{api_zone.apiName} started")

          Connection.send_message_to_server(
            get(this, :_connection),
            this,
            method,
            validated_params,
            Map.merge(api_zone, %{signal: signal, timeout: timeout, on_reply: on_reply})
          )
        else
          # Since this api call is either internal, or has already been reported/traced once,
          # passing as internal.
          Connection.send_message_to_server(get(this, :_connection), this, method, validated_params, %{
            internal: true,
            signal: signal,
            timeout: timeout,
            on_reply: on_reply
          })
        end
      end,
      %{internal: internal}
    )
  end

  def _wrap_api_call(this, func, options \\ %{}) do
    # Elixir only: a disposed object has no fields left (see `channel_call/4`).
    logger = if Heap.alive?(this), do: get(this, :_logger)
    existing_api_zone = Zones.data(:apiZone)

    if existing_api_zone do
      func.(existing_api_zone)
    else
      stack_trace = ClientStackTrace.capture_library_stack_trace()
      api_name = stack_trace.apiName

      api_name =
        if String.starts_with?(api_name, "_") or String.contains?(api_name, "._"),
          do: options[:title] || api_name,
          else: api_name

      api_zone = %{
        title: options[:title],
        apiName: api_name,
        frames: stack_trace.frames,
        internal: options[:internal] || false,
        reported: false,
        userData: nil,
        callId: nil
      }

      try do
        result = Zones.with(:apiZone, api_zone, fn -> func.(api_zone) end)

        if !options[:internal] do
          log_api_call(logger, "<= #{api_zone.apiName} succeeded")
          ClientInstrumentation.on_api_call_end(get(this, :_instrumentation), api_zone)
        end

        result
      rescue
        e ->
          # const innerError = ...  -- not ported: stack rewriting (Elixir keeps __STACKTRACE__)
          e =
            if api_zone.apiName != "" and !String.contains?(api_zone.apiName, "<anonymous>") and
                 Map.has_key?(e, :message),
               do: %{e | message: api_zone.apiName <> ": " <> Exception.message(e)},
               else: e

          # const stackFrames = ...; e.stack = ...  -- not ported: stack rewriting

          if !options[:internal] do
            api_zone = Map.put(api_zone, :error, e)
            log_api_call(logger, "<= #{api_zone.apiName} failed")
            ClientInstrumentation.on_api_call_end(get(this, :_instrumentation), api_zone)
          end

          reraise e, __STACKTRACE__
      end
    end
  end

  # toJSON  -- not ported (Inspect shows the handle)

  # `logger` is the `logger:` option, `%{isEnabled: fun, log: fun}`. JS functions take any number of arguments.
  defp log_api_call(logger, message) do
    if logger && ClientHelper.call_function(logger.isEnabled, ["api", "info"]),
      do: ClientHelper.call_function(logger.log, ["api", "info", message, [], %{color: "cyan"}])

    # debugLogger.log('api', message)
    Logger.debug("pw:api " <> message)
  end

  defp t_channel_impl_to_wire(names, arg, path, _context) do
    if is_channel_owner(arg) and (names == :* or get(arg, :_type) in names),
      do: %{guid: arg.guid},
      else: raise(ValidationError, message: "#{path}: expected channel #{channel_names(names)}")
  end

  @doc false
  def channel_names(:*), do: "*"
  def channel_names(names), do: Enum.join(names, ",")
end

defmodule Mix.Playwright.NoticesTest do
  use ExUnit.Case, async: true

  alias Mix.Playwright.Notices

  @moduletag :tmp_dir

  @apache """
  /**
   * Copyright 2018 Google Inc. All rights reserved.
   * Modifications copyright (c) Microsoft Corporation.
   *
   * Licensed under the Apache License, Version 2.0 (the "License");
   */
  """

  @mit """
  /**
   * Copyright Joyent, Inc. and other Node contributors.
   *
   * Permission is hereby granted, free of charge, to any person obtaining a
   * The above copyright notice and this permission notice shall be included
   */
  """

  setup %{tmp_dir: upstream} do
    File.write!(Path.join(upstream, "a.ts"), @apache)
    File.write!(Path.join(upstream, "b.ts"), "#!/usr/bin/env node\n" <> @mit)
    File.write!(Path.join(upstream, "c.ts"), "// no header\n")
    :ok
  end

  test "put/3 adds the header of the @upstream files, idempotently", %{tmp_dir: upstream} do
    source = """
    # A comment.
    defmodule A do
      @upstream "a.ts"

      defmodule B do
        @upstream "b.ts"
      end
    end
    """

    expected = """
    # Copyright 2018 Google Inc. All rights reserved.
    # Modifications copyright (c) Microsoft Corporation.
    # Copyright Joyent, Inc. and other Node contributors.
    # Ported to Elixir and modified by the playwright_ex authors.
    # SPDX-License-Identifier: Apache-2.0 AND MIT

    """

    assert Notices.put(upstream, "lib/a.ex", source) == expected <> source
    assert Notices.put(upstream, "lib/a.ex", expected <> source) == expected <> source
    assert Notices.strip(expected <> source) == source
  end

  test "put/3 drops the header of a file with no upstream source", %{tmp_dir: upstream} do
    source = "defmodule A do\nend\n"
    header = "# Copyright (c) Microsoft Corporation.\n# SPDX-License-Identifier: Apache-2.0\n\n"
    assert Notices.put(upstream, "lib/a.ex", header <> source) == source
    assert Notices.put(upstream, "lib/a.ex", source) == source
  end

  test "generated?/1 looks past the header" do
    assert Notices.generated?("# Copyright x\n# SPDX-License-Identifier: MIT\n\n# This file is generated by y\n")
    refute Notices.generated?("defmodule A do\nend\n")
  end

  test "an upstream file without a header is under upstream's root license and NOTICE", %{tmp_dir: upstream} do
    assert Notices.notice(upstream, "c.ts") == {["Copyright (c) Microsoft Corporation."], "Apache-2.0"}
  end

  test "put/3 is idempotent for a header-less upstream file", %{tmp_dir: upstream} do
    source = "defmodule A do\n  @upstream \"c.ts\"\nend\n"
    once = Notices.put(upstream, "lib/a.ex", source)
    assert once =~ "# Copyright (c) Microsoft Corporation.\n"
    assert Notices.put(upstream, "lib/a.ex", once) == once
  end

  test "check_runner_sources/3: unlisted runner citations outside src/matchers, and stale listed paths",
       %{tmp_dir: upstream} do
    File.mkdir_p!(Path.join(upstream, "packages/playwright/src/worker"))
    File.write!(Path.join(upstream, "packages/playwright/src/worker/testInfo.ts"), "")

    files = [
      {"lib/playwright/test.ex",
       """
       # `packages/playwright/src/worker/testInfo.ts` and `packages/playwright/types/test.d.ts`,
       # `packages/playwright/src/matchers/expect.ts`, `packages/playwright-core/src/client/page.ts`,
       # again `packages/playwright/types/test.d.ts`, and a bare `dispatcher.ts`.
       """}
    ]

    listed = ["packages/playwright/src/worker/testInfo.ts", "packages/playwright/src/gone.ts"]

    assert Notices.check_runner_sources(upstream, files, listed) == [
             "lib/playwright/test.ex: cites packages/playwright/types/test.d.ts, " <>
               "list it in Mix.Playwright.Notices @watched with a reason",
             "packages/playwright/src/gone.ts: a runner source in Mix.Playwright.Notices, but not found upstream, drop it"
           ]
  end

  test "runner_sources/0: sorted, unique, the runner's (not the matchers' or the client's)" do
    sources = Notices.runner_sources()
    assert sources == sources |> Enum.uniq() |> Enum.sort()
    assert "packages/playwright/src/worker/testInfo.ts" in sources
    assert "packages/playwright/src/worker/timeoutManager.ts" in sources
    assert Enum.all?(sources, &String.starts_with?(&1, "packages/playwright/"))
    refute Enum.any?(sources, &String.starts_with?(&1, "packages/playwright/src/matchers/"))
  end
end

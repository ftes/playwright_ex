defmodule PlaywrightEx.MixProject do
  use Mix.Project

  @version "0.16.0"
  @source_url "https://github.com/ftes/playwright_ex"
  @description """
  Elixir client for Playwright: a port of the official JavaScript client.
  """

  def project do
    [
      app: :playwright_ex,
      version: @version,
      description: @description,
      elixir: "~> 1.18",
      elixirc_paths: elixirc_paths(Mix.env()),
      deps: deps(),
      package: package(),
      name: "PlaywrightEx",
      source_url: @source_url,
      docs: docs(),
      aliases: aliases(),
      dialyzer: [
        plt_local_path: "priv/plts/project.plt",
        plt_core_path: "priv/plts/core.plt",
        plt_add_apps: [:ex_unit, :mix]
      ]
    ]
  end

  # Run "mix help compile.app" to learn about applications.
  def application do
    [
      mod: {PlaywrightEx.Application, []},
      # inets/ssl/public_key: driver download (`PlaywrightEx.Driver`).
      # ex_unit: matchers raise ExUnit.AssertionError (`PlaywrightEx.Expect`), optional outside tests.
      extra_applications: [:logger, :inets, :ssl, :crypto, :public_key, ex_unit: :optional]
    ]
  end

  defp elixirc_paths(:test), do: ["lib", "test/support"]
  defp elixirc_paths(_), do: ["lib"]

  # Run "mix help deps" to learn about dependencies.
  defp deps do
    [
      {:ex_doc, ">= 0.39.0 and < 1.0.0", only: :dev, runtime: false},
      {:credo, "~> 1.7", only: [:dev, :test], runtime: false},
      {:dialyxir, "~> 1.4", only: [:dev, :test], runtime: false},
      # The port of upstream tests/config/testserver.
      {:bandit, "~> 1.6", only: :test}
    ]
  end

  defp package do
    [
      licenses: ["MIT"],
      links: %{"Github" => @source_url},
      exclude_patterns: ~w(priv/plts)
    ]
  end

  def cli do
    [
      preferred_envs: [
        format: :test,
        setup: :test,
        check: :test
      ]
    ]
  end

  defp docs do
    [
      main: "readme",
      source_ref: "v#{@version}",
      extras: [
        "README.md": [title: "Overview"],
        "guides/migration.md": [title: "Migrating to 1.64"],
        "CHANGELOG.md": [title: "Changelog"]
      ],
      nest_modules_by_prefix: [PlaywrightEx],
      # The changelog names functions of the API before the restructure.
      skip_undefined_reference_warnings_on: ["CHANGELOG.md"],
      groups_for_modules: [
        # Generated by `mix playwright_ex.gen.api`.
        API: &(to_string(&1[:source_path]) =~ "/lib/playwright_ex/api/"),
        Client: ~r/^PlaywrightEx\.Client\./,
        Matchers: ~r/^PlaywrightEx\.Matchers\./,
        Protocol: ~r/^PlaywrightEx\.Protocol\./,
        Runtime: ~r/^PlaywrightEx\.(Runtime|Transport)\./
      ]
    ]
  end

  defp aliases do
    [
      setup: ["deps.get", "playwright_ex.install -- chromium"],
      check: [
        "format --check-formatted",
        "credo",
        "compile --warnings-as-errors",
        "dialyzer --format github --format dialyxir",
        "playwright_ex.parity",
        "test --warnings-as-errors"
      ]
    ]
  end
end

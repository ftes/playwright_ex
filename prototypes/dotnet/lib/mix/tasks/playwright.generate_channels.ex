defmodule Mix.Tasks.Playwright.GenerateChannels do
  @shortdoc "Generates lib/playwright/transport/protocol/generated from protocol.yml"
  @moduledoc """
  Elixir port of upstream `utils/generate_dotnet_channels.js` (playwright JS repo).

  Like the .NET generator it emits one module per protocol interface initializer
  (`<Name>Initializer`) and one per protocol object type, into
  `lib/playwright/transport/protocol/generated/`. Additionally (not in .NET) it emits
  `Playwright.Transport.Protocol.Commands` with the parameter names of every command, which
  `Connection` can use to validate the hand-written Core layer against the spec.

      mix playwright.generate_channels <playwright-js-repo> [<playwright-core-dir>]
  """
  use Mix.Task

  @out_dir "lib/playwright/transport/protocol/generated"
  @header "# Generated by `mix playwright.generate_channels` from packages/protocol/spec/*.yml. Do not edit.\n"
  # upstream: generate_dotnet_channels.js:252 (skip-list for object types)
  @skipped_objects ~w(AXNode SetNetworkCookie NetworkCookie IndexedDBDatabase SetOriginStorage OriginStorage)

  @impl Mix.Task
  def run([js_repo | rest]) do
    core_dir = List.first(rest) || "../node_modules/playwright-core"
    script = Path.join(:code.priv_dir(:playwright_dotnet_port), "protocol_to_json.js")
    {json, 0} = System.cmd("node", [script, js_repo, core_dir])
    {protocol, _, _} = JSON.decode(json, [], object_finish: &ordered/2)

    File.rm_rf!(@out_dir)
    File.mkdir_p!(@out_dir)

    # upstream: generate_dotnet_channels.js:224
    channels = for {name, %{"type" => "interface"}} <- protocol, into: MapSet.new(), do: name
    inherits = for {name, %{"type" => "interface", "extends" => ext}} <- protocol, into: %{}, do: {name, ext}
    mixins = for {name, %{"type" => "mixin"} = v} <- protocol, into: %{}, do: {name, v}
    ctx = %{channels: channels, inherits: inherits, mixins: mixins, protocol: protocol}

    # upstream: generate_dotnet_channels.js:243
    for {name, item} <- entries(protocol) do
      case item do
        %{"type" => "interface"} ->
          initializer_name = name <> "Initializer"
          props = inherited_initializer(ctx, name) ++ entries(item["initializer"] || %{})
          object_type(ctx, props, initializer_name)

        %{"type" => "object", "properties" => props} ->
          if name not in @skipped_objects and entries(props) != [], do: object_type(ctx, entries(props), name)

        _ ->
          :ok
      end
    end

    write_commands(ctx)
    Mix.shell().info("Generated #{length(File.ls!(@out_dir))} files in #{@out_dir}")
  end

  # .NET uses C# inheritance (`class ElementHandleInitializer : JSHandleInitializer`); Elixir structs flatten.
  defp inherited_initializer(ctx, name) do
    case ctx.inherits[name] do
      nil -> []
      parent -> inherited_initializer(ctx, parent) ++ entries(ctx.protocol[parent]["initializer"] || %{})
    end
  end

  # upstream: generate_dotnet_channels.js:72 inlineType -> returns a decoder spec instead of a C# type
  defp inline_type(ctx, type, _name, _level) when is_binary(type) do
    {type, optional} = strip_optional(type)

    cond do
      type in ~w(binary json string boolean number int float undefined SerializedValue SerializedArgument) ->
        {:raw, optional}

      match?(%{"type" => "enum"}, ctx.protocol[type]) ->
        {:enum, optional}

      MapSet.member?(ctx.channels, type) ->
        {{:channel, type}, optional}

      type == "Channel" ->
        {{:channel, "*"}, optional}

      match?(%{"type" => "object", "properties" => p} when map_size(p) > 1, ctx.protocol[type]) and
          type not in @skipped_objects ->
        {{:module, type}, optional}

      true ->
        {:raw, optional}
    end
  end

  defp inline_type(ctx, %{"type" => "array" <> opt} = type, name, level) do
    {inner, _} = inline_type(ctx, type["items"], name, level)
    {{:array, inner}, opt == "?"}
  end

  # .NET: enums containing "networkidle" become the LoadState enum, others stay strings
  defp inline_type(_ctx, %{"type" => "enum" <> _} = type, _name, _level),
    do: if("networkidle" in type["literals"], do: {:enum, false}, else: {:raw, false})

  defp inline_type(ctx, %{"type" => "object" <> opt} = type, name, level) do
    optional = opt == "?"

    case process_custom_type(type, name) do
      nil when level >= 1 ->
        object_type(ctx, entries(type["properties"] || %{}), name)
        {{:module, name}, optional}

      nil ->
        {:raw, optional}

      custom ->
        {custom, optional}
    end
  end

  defp strip_optional(type) do
    if String.ends_with?(type, "?"), do: {String.trim_trailing(type, "?"), true}, else: {type, false}
  end

  # upstream: generate_dotnet_channels.js:126 properties
  defp properties(ctx, props, parent_name, level) do
    Enum.flat_map(props, fn
      {"android", _} -> []
      {"electron", _} -> []
      {"$mixin" <> _, mixin} -> properties(ctx, entries(ctx.mixins[mixin]["properties"]), parent_name, level)
      {name, value} -> [{name, elem(inline_type(ctx, value, parent_name <> title_case(name), level + 1), 0)}]
    end)
  end

  # upstream: generate_dotnet_channels.js:150 objectType + :232 writeCSharpClass
  defp object_type(ctx, props, class_name) do
    if class_name != "SerializedArgument" do
      fields = properties(ctx, props, class_name, 0)
      write_module(class_name, fields)
    end
  end

  # upstream: generate_dotnet_channels.js:264 processCustomType (hand-written .NET types -> raw maps here)
  defp process_custom_type(type, full_name) do
    p = type["properties"] || %{}

    cond do
      Map.has_key?(p, "name") and Map.has_key?(p, "value") and p["name"] == "string" and p["value"] == "string" -> :raw
      Map.has_key?(p, "width") and Map.has_key?(p, "height") -> :raw
      Map.has_key?(p, "url") and Map.has_key?(p, "lineNumber") -> :raw
      Map.has_key?(p, "name") and Map.has_key?(p, "descriptor") -> :raw
      full_name == "BrowserContextInitializerOptions" -> :raw
      true -> nil
    end
  end

  defp write_module(class_name, fields) do
    mod = "Playwright.Transport.Protocol.#{class_name}"
    keys = Enum.map_join(fields, ", ", fn {name, _} -> ":" <> field(name) end)

    decoders =
      Enum.map_join(fields, ",\n", fn {name, kind} -> "      #{field(name)}: #{decoder(kind, ~s(json["#{name}"]))}" end)

    encoders = Enum.map_join(fields, ",\n", fn {name, _} -> ~s(      "#{name}" => value.#{field(name)}) end)

    source = """
    #{@header}
    defmodule #{mod} do
      @moduledoc false
      alias Playwright.Transport.Converters

      defstruct [#{keys}]

      def from_json(nil, _connection), do: nil

      def from_json(json, connection) do
        _ = {json, connection}

        %__MODULE__{
    #{decoders}
        }
      end

      def to_json(%__MODULE__{} = value) do
        _ = value

        Converters.drop_nils(%{
    #{encoders}
        })
      end
    end
    """

    path = Path.join(@out_dir, Macro.underscore(class_name) <> ".ex")
    File.write!(path, Code.format_string!(source) |> IO.iodata_to_binary() |> Kernel.<>("\n"))
  end

  defp decoder(:raw, expr), do: expr
  defp decoder(:enum, expr), do: "Converters.to_enum(#{expr})"
  defp decoder({:channel, _}, expr), do: "Converters.to_channel_owner(#{expr}, connection)"
  defp decoder({:module, name}, expr), do: "Playwright.Transport.Protocol.#{name}.from_json(#{expr}, connection)"
  defp decoder({:array, :raw}, expr), do: expr
  defp decoder({:array, inner}, expr), do: "Converters.map_list(#{expr}, fn item -> #{decoder(inner, "item")} end)"

  defp write_commands(ctx) do
    lines =
      for {name, %{"type" => "interface"} = item} <- entries(ctx.protocol),
          {method, cmd} <- entries(all_commands(ctx, name, item)) do
        params = param_names(ctx, entries((cmd || %{})["parameters"] || %{}))
        ~s|  def params(#{inspect(name)}, #{inspect(method)}), do: #{inspect(Enum.sort(params))}|
      end

    source = """
    #{@header}
    defmodule Playwright.Transport.Protocol.Commands do
      @moduledoc false
    #{Enum.join(lines, "\n")}
      def params(_interface, _method), do: :unknown
    end
    """

    File.write!(Path.join(@out_dir, "commands.ex"), Code.format_string!(source) |> IO.iodata_to_binary() |> Kernel.<>("\n"))
  end

  defp param_names(ctx, props) do
    Enum.flat_map(props, fn
      {"$mixin" <> _, mixin} -> param_names(ctx, entries(ctx.mixins[mixin]["properties"]))
      {name, _} -> [name]
    end)
  end

  defp all_commands(ctx, name, item) do
    own = item["commands"] || %{}

    case ctx.inherits[name] do
      nil -> own
      parent ->
        inherited = all_commands(ctx, parent, ctx.protocol[parent])
        order = (inherited["__order__"] || []) ++ (own["__order__"] || [])
        inherited |> Map.merge(own) |> Map.put("__order__", Enum.uniq(order))
    end
  end

  # JSON.decode object_finish callback: keep the spec key order (generated output diffs cleanly across rolls)
  defp ordered(acc, old_acc) do
    list = Enum.reverse(acc)
    {list |> Map.new() |> Map.put("__order__", Enum.map(list, &elem(&1, 0))), old_acc}
  end

  defp entries(map), do: Enum.map(map["__order__"] || [], &{&1, map[&1]})

  defp field(name), do: Macro.underscore(name)
  defp title_case(<<c::utf8, rest::binary>>), do: String.upcase(<<c::utf8>>) <> rest
end

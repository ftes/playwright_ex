defmodule GenApi do
  @moduledoc """
  Elixir counterpart of playwright-java's `tools/api-generator` (ApiGenerator.java).

  Reads `priv/api.json` (produced by upstream `utils/doclint/generateApiJson.js`, exactly like
  `scripts/generate_api.sh` in playwright-java) and, for each configured class, writes
  `lib/playwright/generated/<class>.ex` containing:

    * one `<Method>Options` struct per method (typespec, `__json_names__/0` wire-name map, `new/1`),
    * one documented, spec'ed public function per Java method/property that has a counterpart in the hand-written
      `*Impl` module (detected by scanning `def` names in the Impl source), delegating with Java's argument order,
    * a "Not yet ported" list in the moduledoc for the remaining Java members (parity report on every roll).

  Usage (standalone script, so it runs before the project compiles): `elixir scripts/gen_api.exs [path/to/api.json]`
  """
  @classes [
    {"Playwright", "Playwright", "PlaywrightImpl", "playwright"},
    {"BrowserType", "Playwright.BrowserType", "BrowserTypeImpl", "browser_type"},
    {"Browser", "Playwright.Browser", "BrowserImpl", "browser"},
    {"BrowserContext", "Playwright.BrowserContext", "BrowserContextImpl", "browser_context"},
    {"Page", "Playwright.Page", "PageImpl", "page"},
    {"Frame", "Playwright.Frame", "FrameImpl", "frame"},
    {"Locator", "Playwright.Locator", "LocatorImpl", "locator"},
    {"Download", "Playwright.Download", "DownloadImpl", "download"},
    {"PageAssertions", "Playwright.Assertions.PageAssertions", "PageAssertionsImpl", "page_assertions"},
    {"LocatorAssertions", "Playwright.Assertions.LocatorAssertions", "LocatorAssertionsImpl", "locator_assertions"}
  ]
  @static [{"Playwright", "create"}]
  @reserved ~w(not and or in when fn do end true false nil)

  def run(args) do
    api_path = List.first(args) || "priv/api.json"
    api = api_path |> File.read!() |> JSON.decode!() |> Map.new(&{&1["name"], &1})
    class_modules = Map.new(@classes, fn {name, mod, _, _} -> {name, mod} end)

    for {name, module, impl, receiver} <- @classes do
      clazz = Map.fetch!(api, name)
      impl_source = Path.join("lib/playwright/impl", Macro.underscore(impl) <> ".ex")
      implemented = impl_source |> File.read!() |> then(&Regex.scan(~r/^\s*def\s+([a-z_0-9?!]+)\(/m, &1)) |> MapSet.new(fn [_, n] -> n end)
      code = gen_class(clazz, module, "Playwright.Impl." <> impl, receiver, implemented, class_modules)
      out = Path.join("lib/playwright/generated", Macro.underscore(String.replace_prefix(module, "Playwright.", "")) <> ".ex")
      out = if module == "Playwright", do: "lib/playwright/generated/playwright.ex", else: out
      File.mkdir_p!(Path.dirname(out))
      File.write!(out, Code.format_string!(code, line_length: 120) |> IO.iodata_to_binary() |> Kernel.<>("\n"))
      IO.puts("generated #{out}")
    end
  end

  defp java?(%{"langs" => %{"only" => only}}), do: "java" in only
  defp java?(_), do: true

  defp alias_of(%{"langs" => %{"aliases" => %{"java" => a}}}), do: a
  defp alias_of(%{"name" => n}), do: n

  defp java_type(%{"langs" => %{"types" => %{"java" => t}}}), do: t
  defp java_type(%{"type" => t}), do: t

  defp snake(name) do
    s = Macro.underscore(name)
    if s in @reserved, do: s <> "_", else: s
  end

  defp gen_class(clazz, module, impl, receiver, implemented, class_modules) do
    members = for m <- clazz["members"], java?(m), not String.contains?(m["name"], "#"), do: m
    methods = Enum.filter(members, &(&1["kind"] in ["method", "property"]))

    {ported, unported} =
      Enum.split_with(methods, fn m -> MapSet.member?(implemented, snake(alias_of(m))) end)

    options_modules = methods |> Enum.map(&gen_options(&1, class_modules)) |> Enum.reject(&is_nil/1) |> Enum.uniq()
    functions = Enum.map(ported, &gen_function(&1, clazz["name"], impl, receiver, class_modules))

    """
    # GENERATED by `elixir scripts/gen_api.exs` from api.json -- do not edit.
    defmodule #{module} do
      @moduledoc #{inspect(doc(clazz["comment"]) <> "\n\nNot yet ported: " <> Enum.map_join(unported, ", ", &snake(alias_of(&1))) <> ".")}
      @type t :: #{impl}.t()

      #{Enum.join(options_modules, "\n\n")}

      #{Enum.join(functions, "\n\n")}
    end
    """
  end

  defp options_arg(m), do: Enum.find(java_args(m), &(&1["name"] == "options" and &1["type"]["properties"]))

  defp java_args(m), do: for(a <- m["args"] || [], java?(a), do: a)

  defp options_module_name(m) do
    a = alias_of(m)
    String.upcase(String.first(a)) <> String.slice(a, 1..-1//1) <> "Options"
  end

  defp option_props(opt) do
    opt["type"]["properties"] |> Enum.filter(&java?/1) |> Enum.uniq_by(& &1["name"])
  end

  defp gen_options(m, class_modules) do
    case options_arg(m) do
      nil ->
        nil

      opt ->
        props = option_props(opt)
        fields = Enum.map(props, &{snake(&1["name"]), &1})

        """
        defmodule #{options_module_name(m)} do
          @moduledoc false
          @type t :: %__MODULE__{#{Enum.map_join(fields, ", ", fn {f, p} -> "#{f}: #{typespec(java_type(p), class_modules)} | nil" end)}}
          defstruct [#{Enum.map_join(fields, ", ", fn {f, _} -> ":" <> f end)}]
          @doc false
          def __json_names__, do: %{#{Enum.map_join(fields, ", ", fn {f, p} -> "#{f}: #{inspect(p["name"])}" end)}}
          def new(%__MODULE__{} = options), do: options
          def new(options) when is_list(options) or is_map(options), do: struct!(__MODULE__, options)
        end
        """
    end
  end

  defp gen_function(m, class_name, impl, receiver, class_modules) do
    name = snake(alias_of(m))
    static? = {class_name, m["name"]} in @static
    args = java_args(m)
    opt = options_arg(m)
    positional = Enum.reject(args, &(&1 == opt or &1["type"]["name"] in ["Runnable", "function"] and &1["name"] == "callback"))
    callback = Enum.find(args, &(&1["name"] == "callback"))

    params =
      (if static?, do: [], else: [receiver]) ++
        Enum.map(positional, fn a -> snake(a["name"]) <> if(a["required"], do: "", else: " \\\\ nil") end) ++
        if(callback, do: ["callback"], else: []) ++ if(opt, do: ["options \\\\ []"], else: [])

    impl_args =
      (if static?, do: [], else: [receiver]) ++
        Enum.map(args, fn a ->
          cond do
            a == opt -> "#{options_module_name(m)}.new(options)"
            a == callback -> "callback"
            true -> snake(a["name"])
          end
        end)

    spec_args =
      (if static?, do: [], else: ["t()"]) ++
        Enum.map(positional, &typespec(java_type(&1), class_modules)) ++
        if(callback, do: ["(-> any())"], else: []) ++ if(opt, do: ["keyword()"], else: [])

    void? = m["type"]["name"] == "void"
    call = "#{impl}.#{name}(#{Enum.join(impl_args, ", ")})"
    body = if void?, do: "_ = #{call}\n:ok", else: call

    opts_doc =
      if opt,
        do:
          "\n\n## Options\n\n" <>
            Enum.map_join(option_props(opt), "\n", fn p -> "  * `:#{snake(p["name"])}` - #{first_sentence(p["comment"])}" end),
        else: ""

    """
    @doc #{inspect(doc(m["comment"]) <> opts_doc)}
    @doc since: #{inspect(m["since"])}
    @spec #{name}(#{Enum.join(spec_args, ", ")}) :: #{typespec(m["type"], class_modules)}
    def #{name}(#{Enum.join(params, ", ")}) do
      #{body}
    end
    """
  end

  defp doc(nil), do: ""
  defp doc(comment), do: comment |> String.replace(~r/```.*?```\n*/s, "") |> String.trim()

  defp first_sentence(nil), do: ""
  defp first_sentence(c), do: c |> doc() |> String.replace("\n", " ") |> String.split(~r/(?<=\.)\s/, parts: 2) |> hd()

  defp typespec(%{"union" => union}, cm) do
    if Enum.all?(union, &String.starts_with?(&1["name"], "\"")),
      do: union |> Enum.map(&(":" <> inspect(String.trim(&1["name"], "\"")))) |> Enum.join(" | ") |> String.replace(":\"", "\"") |> fix_atoms(),
      else: union |> Enum.map(&typespec(&1, cm)) |> Enum.uniq() |> Enum.join(" | ")
  end

  defp typespec(%{"name" => name} = t, cm) do
    case name do
      "string" -> "String.t()"
      "boolean" -> "boolean()"
      "int" -> "integer()"
      "float" -> "number()"
      "path" -> "Path.t()"
      "RegExp" -> "Regex.t()"
      "Buffer" -> "binary()"
      "void" -> ":ok"
      "null" -> "nil"
      "undefined" -> "nil"
      "Array" -> "[" <> typespec(hd(t["templates"] || [%{"name" => "any"}]), cm) <> "]"
      "Object" -> "map()"
      "function" -> "fun()"
      "Runnable" -> "(-> any())"
      n -> if Map.has_key?(cm, n), do: cm[n] <> ".t()", else: "term()"
    end
  end

  defp fix_atoms(s), do: s |> String.split(" | ") |> Enum.map_join(" | ", &(":" <> String.trim(&1, "\"") |> atomize()))
  defp atomize(":" <> a), do: if(a =~ ~r/^[a-z_][a-zA-Z0-9_]*$/, do: ":" <> a, else: ":" <> inspect(a))
end

GenApi.run(System.argv())
